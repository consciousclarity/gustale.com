-- A row here means: this identity is a SYSTEM ACTOR, not a person. It
-- has NO login in "user", NO email, NO password, NO session and NO
-- publish credential -- and it may act ONLY inside the function that
-- owns it (recipe_auto_publish(), SECURITY DEFINER).
--
-- The `kind` CHECK is the point: there is no 'human' kind, so this
-- table can never hold a person.
CREATE TABLE IF NOT EXISTS public.service_accounts (
  id         uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  actor      text NOT NULL UNIQUE,
  kind       text NOT NULL CHECK (kind IN ('system')),
  purpose    text NOT NULL,
  created_at timestamptz NOT NULL DEFAULT now(),
  revoked_at timestamptz
);

COMMENT ON TABLE public.service_accounts IS
'The system actors. A row here is a SYSTEM ACTOR, not a person: no login, '
'no email, no password, no session, no publish credential. It may act '
'ONLY inside the SECURITY DEFINER function that owns it. The kind CHECK '
'admits only ''system'', so this table can never hold a person '
'(ADR-007-A1 §2.4).';

-- The ONE row. It is a ROW, not an account.
--
-- No account is created: there is no row in "user", no email, no
-- password, no session and no credential (ADR-007-A1 §2.4.4).
INSERT INTO public.service_accounts (actor, kind, purpose)
VALUES ('system:auto-publish', 'system',
        'The recipes auto-publish function. Acts only inside recipe_auto_publish().')
ON CONFLICT (actor) DO NOTHING;

-- ═══════════════════════════════════════════════════════════════════════
-- PART 4 -- THE AUTHORISATION TOKEN (§2.4.3, §8.4)
-- ═══════════════════════════════════════════════════════════════════════

-- THE TOKEN TABLE. This is the "marker" of §8.4, and it is a TABLE
-- rather than a GUC because a GUC is forgeable: `set_config` on a
-- custom GUC can be called by any role, so a GUC marker -- and a
-- nonce stored in another GUC -- is a string the ATTACKER chooses.
--
-- What is unforgeable is a row in a table the attacker cannot write.
-- So:
--
--   * `recipe_auto_publish()` (SECURITY DEFINER) generates a token and
--     writes it here. It never leaves the database.
--   * `statement_set_status()` reads it, compares it with the token it
--     was handed, and the row is DELETED when the function returns --
--     so it is single-use and cannot be replayed.
--   * the APPLICATION ROLE HAS NO PRIVILEGE ON THIS TABLE, so it
--     cannot insert a token of its own.
--
-- The table's GRANTS are the second half of the check: because
-- `statement_set_status()` is SECURITY INVOKER, it reads this table
-- under the CALLER's privileges. The legitimate caller is
-- `recipe_auto_publish()` running as its owner -- the role that owns
-- this table -- so the read succeeds. Any other caller gets
-- "permission denied for table recipe_auto_publish_token", which is
-- the refusal.
--
-- So the branch needs THREE things at once, and an attacker must
-- forge all three:
--   a. a token row that matches (the attacker cannot write one);
--   b. `current_user` = the owner of `recipe_auto_publish()` (inside a
--      SECURITY DEFINER function `current_user` IS the owner);
--   c. the token is live (it is deleted on the way out).
CREATE TABLE IF NOT EXISTS public.recipe_auto_publish_token (
  token       uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  created_at  timestamptz NOT NULL DEFAULT now(),
  -- The recipe the token was minted for. A token for one recipe cannot
  -- authorise a transition about another.
  --
  -- It is NULLABLE, and that is deliberate: the migration's forge
  -- proof mints a token with no recipe -- the strongest forgery there
  -- is -- and the branch refuses it. A NOT NULL column would have
  -- made that forgery impossible to express, and the proof weaker.
  recipe_id   uuid REFERENCES public.recipes(id) ON DELETE CASCADE,
  -- The txid that minted it. A token minted in another transaction is
  -- not honoured, so a token cannot be carried across a commit.
  --
  -- It is NOT DEFAULTED: the minting code always sets it explicitly,
  -- and a token with no txid would have no transaction to bind to.
  txid        bigint NOT NULL
);

COMMENT ON TABLE public.recipe_auto_publish_token IS
'The authorisation token that proves the caller of statement_set_status() '
'IS recipe_auto_publish() (ADR-007-A1 §2.4.3, §8.4). A GUC marker would '
'not do: set_config on a custom GUC can be called by any role, so the '
'marker would be a string the attacker chooses. This is a TABLE the '
'application role has no privilege on, so the token is a fact the '
'attacker cannot manufacture. The row is single-use: recipe_auto_publish() '
'deletes it when it returns.';

-- THE APPLICATION ROLE GETS NO PRIVILEGE ON THE TOKEN TABLE.
--
-- This is the point of the table. `ci-migration-role.sql` grants the
-- bot role `SELECT, INSERT, UPDATE, DELETE, TRUNCATE, REFERENCES,
-- TRIGGER` on every table by default -- so without an explicit REVOKE
-- the application role could INSERT its own token and forge the
-- system actor. The REVOKE is therefore part of the migration, not an
-- afterthought, and the proof asserts it.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gustale') THEN
    EXECUTE 'REVOKE ALL ON public.recipe_auto_publish_token FROM gustale';
  END IF;
END;
$$;

-- ═══════════════════════════════════════════════════════════════════════
-- PART 5 -- THE SETTINGS: THE KILL SWITCH AND THE DAILY CAP
-- ═══════════════════════════════════════════════════════════════════════

-- A single-row table, read by the auto-publish function on EVERY
-- invocation, so flipping the switch takes effect on the next call --
-- no restart, no deploy (ADR-007-A1 §7.1).
--
-- The switch has THREE positions, not two: `enabled` / `disabled` /
-- `enabled_with_cap`. The initial value is `disabled` -- the owner's
-- decision: the switch ships OFF at launch.
--
-- `auto_publish_enabled` is kept as the ADR's §8.1 column name, and the
-- three-position switch is carried by `auto_publish_mode`. The mode is
-- the authoritative switch; `auto_publish_enabled` is the boolean
-- projection of it, so the two cannot disagree.
CREATE TABLE IF NOT EXISTS public.recipe_settings (
  id                     boolean PRIMARY KEY DEFAULT true CHECK (id),
  auto_publish_enabled   boolean NOT NULL DEFAULT false,
  auto_publish_mode      text NOT NULL DEFAULT 'disabled'
                          CHECK (auto_publish_mode IN ('enabled','disabled','enabled_with_cap')),
  auto_publish_daily_cap integer NOT NULL DEFAULT 20 CHECK (auto_publish_daily_cap >= 0),
  updated_at             timestamptz NOT NULL DEFAULT now(),
  updated_by             text
);

COMMENT ON TABLE public.recipe_settings IS
'The recipes settings, in one row. auto_publish_mode is the authoritative '
'kill switch (enabled / disabled / enabled_with_cap) and auto_publish_enabled '
'is its boolean projection, kept in step by a trigger so the two cannot '
'disagree. The initial mode is ''disabled'' -- the switch ships OFF at '
'launch (ADR-007-A1 §7.1). The daily cap ships at 20 (§7.2).';

-- The one row.
INSERT INTO public.recipe_settings (id, auto_publish_enabled, auto_publish_mode, auto_publish_daily_cap)
VALUES (true, false, 'disabled', 20)
ON CONFLICT (id) DO NOTHING;

-- Keep the boolean and the mode in step. Which one is authoritative is
-- the MODE, so a write to either lands on both.
CREATE OR REPLACE FUNCTION public.recipe_settings_switch_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $guard$
BEGIN
  IF NEW.auto_publish_mode IS DISTINCT FROM OLD.auto_publish_mode THEN
    -- The mode changed: the boolean follows it.
    NEW.auto_publish_enabled := (NEW.auto_publish_mode IN ('enabled','enabled_with_cap'));
  ELSIF NEW.auto_publish_enabled IS DISTINCT FROM OLD.auto_publish_enabled THEN
    -- Only the boolean was written: the mode follows it.
    NEW.auto_publish_mode := CASE WHEN NEW.auto_publish_enabled THEN 'enabled' ELSE 'disabled' END;
  END IF;
  RETURN NEW;
END;
$guard$;

COMMENT ON FUNCTION public.recipe_settings_switch_guard() IS
'Keeps auto_publish_enabled and auto_publish_mode in step, so the boolean '
'projection and the authoritative switch can never disagree. The MODE is '
'authoritative; a write to either lands on both.';

DROP TRIGGER IF EXISTS recipe_settings_switch_guard_trg ON public.recipe_settings;
CREATE TRIGGER recipe_settings_switch_guard_trg
  BEFORE UPDATE ON public.recipe_settings
  FOR EACH ROW EXECUTE FUNCTION public.recipe_settings_switch_guard();

