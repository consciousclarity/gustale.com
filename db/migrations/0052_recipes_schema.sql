-- ═══════════════════════════════════════════════════════════════════════
-- PART 9 -- `statement_set_status()` WITH THE SYSTEM-ACTOR BRANCH
-- ═══════════════════════════════════════════════════════════════════════

-- The ONLY way a statement's status changes, with ONE narrow exception.
--
-- WHAT CHANGES AND WHAT DOES NOT
-- -------------------------------
-- This is 0047's function, with ONE branch added and ONE gate widened.
-- Everything else is byte-for-byte 0047's behaviour:
--
--   * the actor is DERIVED from the session token, never supplied by
--     the caller;
--   * the `verified`/`published` transitions require a verified
--     publisher credential, and the refusal names the credential;
--   * the evidence gates are unchanged, except the `published` gate,
--     which is WIDENED (see below);
--   * the write goes through `gustale.statement_gate`, so a direct
--     UPDATE is still refused by `statements_status_gate_trg`.
--
-- THE WIDENED `published` GATE.
--
-- The `published` gate says the statement must be ANCHORED to
-- something. For a DISH statement the anchor is a `sentence_claims` row.
-- A RECIPE statement cannot have one -- `sentence_claims.sentence_id`
-- is FK-bound to `description_sentences(id)`, and a recipe sentence is
-- not a description sentence (ADR-007 Option A), so the recipe's link
-- table is `recipe_claims`. WITHOUT this widening the system actor's
-- publish path could never succeed: every recipe statement would be
-- refused by the gate for want of a dish-side anchor, and the
-- auto-publish function would be dead code.
--
-- The widening is ADDITIVE: a statement still needs a real anchor --
-- it is now a dish anchor OR a recipe anchor, and nothing else changes.
--
-- THE SYSTEM-ACTOR BRANCH.
--
-- Checked FIRST, because the ordinary path below needs a session and
-- a credential, and the system actor has neither.
--
-- THE BRANCH REQUIRES ALL THREE OF:
--   a. a LIVE token in `recipe_auto_publish_token` -- which the
--      caller cannot write, because the application role has no
--      privilege on that table (and the read itself fails with
--      "permission denied" for anyone else, because this function is
--      SECURITY INVOKER and reads under the caller's privileges);
--   b. `current_user` = the owner of `recipe_auto_publish()` -- inside
--      a SECURITY DEFINER function `current_user` IS the owner, and no
--      other role can be that owner;
--   c. the token's `txid` = the current transaction -- so a token
--      cannot be carried across a commit.
--
-- The ADR asks for "current_user AND the marker together"; (a)+(c) are
-- the marker, and (b) is the current_user.
CREATE OR REPLACE FUNCTION public.statement_set_status(p_statement_id uuid, p_to verification_state, p_session_token text)
RETURNS verification_state
LANGUAGE plpgsql
AS $function$
DECLARE
  v_from verification_state;
  v_class claim_class;
  v_ok boolean := false;
  v_role text;
  v_credential_verified boolean := false;
  v_actor text;
  -- THE SYSTEM-ACTOR BRANCH.
  v_is_system_actor boolean := false;
  v_token_recipe uuid;
BEGIN
  -- ── THE SYSTEM-ACTOR BRANCH ───────────────────────────────────────
  --
  -- THE OWNER CHECK COMES FIRST, and that ordering is load-bearing.
  --
  -- This function is SECURITY INVOKER (0047 left it that way, and
  -- 0042's comment depends on it: "it is not SECURITY DEFINER"). So it
  -- reads the token table under the CALLER's privileges. The
  -- legitimate caller is `recipe_auto_publish()` running as its
  -- owner -- the role that owns the token table -- so the read
  -- succeeds. Any OTHER caller has no privilege on that table, and a
  -- read would raise "permission denied for table
  -- recipe_auto_publish_token".
  --
  -- That error would be a CORRECT refusal, but it would be a rude one:
  -- the ordinary publish path -- the API calling this function as the
  -- application role, for an ordinary publisher with a session -- would
  -- fail with a permission error instead of publishing. So the owner
  -- check comes FIRST, and the token is only read when the caller
  -- could be the auto-publish function at all.
  --
  -- (b) THE OWNER. Inside a SECURITY DEFINER function `current_user`
  -- IS the owner. So `current_user = recipe_auto_publish_owner()`
  -- means "the caller reached this function through a SECURITY DEFINER
  -- function owned by the migration role" -- which, in practice, means
  -- `recipe_auto_publish()` itself. It is the half of the ADR's
  -- "current_user AND the marker together" that the marker cannot
  -- supply.
  IF current_user = public.recipe_auto_publish_owner() THEN
    -- (a) THE MARKER. The token the caller presented, looked up in the
    -- table. It must:
    --   * exist (the table is not writable by the application role,
    --     so the caller cannot have manufactured it);
    --   * have been minted in THIS transaction (the `txid` column), so
    --     it cannot be carried across a commit and replayed;
    --   * be for the recipe that owns THIS statement, so a token
    --     minted for one recipe cannot authorise another.
    --
    -- The third clause is checked in the same query, by joining the
    -- token to the statement's recipe. So the query returns a row
    -- ONLY when all three hold at once.
    SELECT t.recipe_id
      INTO v_token_recipe
      FROM public.recipe_auto_publish_token t
      JOIN public.recipe_sentences rs ON rs.recipe_id = t.recipe_id
      JOIN public.recipe_claims rc ON rc.recipe_sentence_id = rs.id
     WHERE t.token::text = p_session_token
       AND t.txid = txid_current()
       AND rc.statement_id = p_statement_id
     LIMIT 1;

    IF v_token_recipe IS NOT NULL THEN
      v_is_system_actor := true;
    END IF;
  END IF;

  IF v_is_system_actor THEN
    -- The actor IS the system actor. It is not derived from a session
    -- (there is no session) and it is not supplied by the caller.
    v_actor := 'system:auto-publish';

    -- The system actor must be a LIVE system actor. A revoked actor
    -- cannot act.
    IF NOT EXISTS (SELECT 1 FROM public.service_accounts s
                    WHERE s.actor = v_actor AND s.revoked_at IS NULL) THEN
      RAISE EXCEPTION
        'the % transition is refused: the system actor % is revoked or unknown',
        p_to, v_actor;
    END IF;
  ELSE
    -- ── WHO IS CALLING ───────────────────────────────────────────────
    --
    -- The ordinary path: the actor is derived from the session token
    -- the caller presented. There is no actor parameter, so a caller
    -- cannot name an identity it does not hold a session for.
    v_actor := session_actor(p_session_token);

    IF v_actor IS NULL THEN
      RAISE EXCEPTION
        'the % transition is refused: no valid session was presented. '
        'The publisher is derived from the session, not from a supplied identity.',
        p_to;
    END IF;
  END IF;

  SELECT status, claim_class INTO v_from, v_class
    FROM statements WHERE id = p_statement_id FOR UPDATE;

  IF NOT FOUND THEN
    RAISE EXCEPTION 'statement % does not exist', p_statement_id;
  END IF;

  -- ── THE PUBLISH CREDENTIAL — positive, default deny ────────────────
  --
  -- The `verified` and `published` transitions require an actor that
  -- HOLDS a credential. There is no name check and no allow-list of
  -- forbidden strings: an actor that is not in `publish_credential` is
  -- refused, whatever it is called.
  --
  -- THE ORDER MATTERS, and it is the order that makes this DEFAULT DENY.
  --
  -- This check runs BEFORE the evidence gates below. Two reasons:
  --
  --   1. An actor without a credential has no business learning whether
  --      the evidence gate for this particular statement is met. The
  --      authorisation is decided first; the content gates are only
  --      reached by an actor who is allowed to ask.
  --
  --   2. With the check AFTER the evidence gates, an unknown actor
  --      attempting `published` on a statement with no sentence anchor
  --      would be refused with "the gate for X -> published is not met"
  --      — a message about the CONTENT, not about the CREDENTIAL. The
  --      credential check would never be reached, and the refusal would
  --      look like an editorial decision rather than an authorisation
  --      failure. The constraint test asserts the refusal message names
  --      the credential, which is what keeps this ordering honest.
  --
  -- THE SYSTEM ACTOR IS EXEMPT FROM THE CREDENTIAL CHECK, AND ONLY
  -- FROM THE CREDENTIAL CHECK. It still runs the full evidence gate
  -- below -- it is exempt from HAVING A CREDENTIAL, not from the gates.
  IF p_to IN ('verified','published') AND NOT v_is_system_actor THEN
    SELECT pc.credential_role,
           (pc.verified_at IS NOT NULL)
      INTO v_role, v_credential_verified
      FROM publish_credential pc
     WHERE pc.actor = v_actor;

    IF v_role IS NULL THEN
      RAISE EXCEPTION
        'the % transition is refused: % holds no publish credential. '
        'Only an account with a verified editor credential may verify or publish a claim.',
        p_to, COALESCE(NULLIF(v_actor, ''), '(none)');
    END IF;

    IF NOT v_credential_verified THEN
      RAISE EXCEPTION
        'the % transition is refused: the publish credential of % has not been verified.',
        p_to, v_actor;
    END IF;

    -- `published` is the stronger act, so it needs the stronger role.
    IF p_to = 'published' AND v_role <> 'publisher' THEN
      RAISE EXCEPTION
        'the % transition is refused: % holds an ''editor'' credential, which may verify but not publish.',
        p_to, v_actor;
    END IF;
  END IF;

  -- The gates, from Q12. These are UNCHANGED by this migration, with
  -- ONE widening, which is explained where it is made.
  CASE p_to
    WHEN 'research_pending' THEN
      v_ok := true;

    WHEN 'under_review' THEN
      v_ok := EXISTS (
        SELECT 1 FROM claim_citations c
         WHERE c.statement_id = p_statement_id
           AND c.excerpt_validated
      );

    WHEN 'verified' THEN
      v_ok := CASE v_class
        WHEN 'documented' THEN
          EXISTS (SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
                   WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
                     AND src.source_class IN ('S1','S2','S3','S4','S5'))
        WHEN 'scholarly_interpretation' THEN
          EXISTS (SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
                   WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
                     AND src.source_class IN ('S1','S2','S3'))
        WHEN 'oral_tradition' THEN
          EXISTS (SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
                   WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
                     AND src.source_class = 'S4')
        WHEN 'disputed' THEN
          (SELECT count(DISTINCT src.source_class) FROM claim_citations c JOIN sources src ON src.id = c.source_id
            WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
              AND src.source_class IN ('S1','S2','S3')) >= 2
        WHEN 'hypothesis' THEN
          EXISTS (SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
                   WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
                     AND src.source_class IN ('S2','S5'))
        ELSE false
      END;

      IF v_ok THEN
        v_ok := EXISTS (
          SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
           WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
             AND src.source_class IN ('S1','S2','S3','S4','S5')
        );
      END IF;

    WHEN 'published' THEN
      -- THE GATE IS WIDENED, AND THIS IS A REAL CHANGE TO AN EXISTING
      -- GATE -- so it is spelled out here.
      --
      -- The `published` gate says: the statement must be ANCHORED to
      -- something. For a DISH statement, the anchor is a
      -- `sentence_claims` row. A RECIPE statement cannot have one --
      -- `sentence_claims.sentence_id` is FK-bound to
      -- `description_sentences(id)`, and a recipe sentence is not a
      -- description sentence (ADR-007 Option A), so the recipe's link
      -- table is `recipe_claims`.
      --
      -- WITHOUT THIS WIDENING, the system actor's publish path could
      -- never succeed: every recipe statement would be refused by the
      -- gate for want of a dish-side anchor, and the auto-publish
      -- function would be dead code.
      --
      -- The widening is ADDITIVE: it adds a second way to satisfy the
      -- anchor test. A statement still needs a real anchor -- it is now
      -- a dish anchor OR a recipe anchor, and nothing else changes.
      v_ok := EXISTS (
        SELECT 1 FROM sentence_claims sc WHERE sc.statement_id = p_statement_id
      ) OR EXISTS (
        SELECT 1 FROM recipe_claims rc WHERE rc.statement_id = p_statement_id
      );

    WHEN 'disputed' THEN
      v_ok := EXISTS (
        SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
         WHERE c.statement_id = p_statement_id AND c.stance = 'supports'
           AND src.source_class IN ('S1','S2','S3')
      ) AND EXISTS (
        SELECT 1 FROM claim_citations c JOIN sources src ON src.id = c.source_id
         WHERE c.statement_id = p_statement_id AND c.stance = 'refutes'
           AND src.source_class IN ('S1','S2','S3')
      );

    ELSE
      v_ok := false;
  END CASE;

  IF NOT v_ok THEN
    RAISE EXCEPTION
      'the gate for % -> % is not met', p_statement_id, p_to;
  END IF;

  -- Authorise THIS write only. The setting is transaction-local, so it
  -- cannot leak into another transaction.
  --
  -- WITHOUT THIS, EVERY CALL FAILS: the `statement_status_gate_trg`
  -- trigger refuses any status change that does not come through the
  -- gate, and the gate IS this setting. The trigger is the reason a
  -- direct UPDATE cannot forge a transition — it is not a substitute
  -- for the gate, it is the thing the gate opens.
  PERFORM set_config('gustale.statement_gate', 'on', true);

  UPDATE statements
     SET status = p_to,
         updated_at = now(),
         -- The publisher is recorded from the DERIVED actor, so the
         -- audit trail names the session's user and not a string the
         -- caller chose.
         verified_by = CASE WHEN p_to = 'verified' THEN v_actor ELSE verified_by END,
         verified_at = CASE WHEN p_to = 'verified' THEN now() ELSE verified_at END,
         published_by = CASE WHEN p_to = 'published' THEN v_actor ELSE published_by END,
         published_at = CASE WHEN p_to = 'published' THEN now() ELSE published_at END
   WHERE id = p_statement_id;

  PERFORM set_config('gustale.statement_gate', 'off', true);

  -- The transition log. Every transition is recorded, with the derived
  -- actor — the same one the credential was checked against.
  INSERT INTO statement_status_log (statement_id, from_status, to_status, actor, gate_ok)
  VALUES (p_statement_id, v_from, p_to, COALESCE(v_actor, '(null)'), true);

  RETURN p_to;
END
$function$;

