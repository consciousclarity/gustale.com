-- ═══════════════════════════════════════════════════════════════════════
-- PART 10 -- THE AUTO-PUBLISH FUNCTION
-- ═══════════════════════════════════════════════════════════════════════

-- Publishes a recipe if, and only if, every HIGH condition is met, the
-- kill switch is on, and the daily cap is not reached.
--
-- Returns the reason on refusal; never raises for a policy refusal.
--
-- SECURITY DEFINER, and it is the ONLY thing that may act as
-- 'system:auto-publish'. It has no session and holds no credential: it
-- IS the actor (§2.4).
--
-- ITS CONTRACT (§8.4):
--   1. evaluates the conditions from §8.3 against the ROWS;
--   2. checks the kill switch and the cap -- THE SWITCH IS CHECKED
--      FIRST, before the recipe is touched (§7.1);
--   3. on success, transitions the recipe's statements to `verified`
--      then `published` THROUGH `statement_set_status()`, with
--      actor = 'system:auto-publish';
--   4. writes `recipe_publish_log`, including `service_account_id`;
--   5. returns a string: the publish reason on success, or the failing
--      condition on refusal.
--
-- It does NOT update `recipes.status` directly. The recipe becomes
-- published because its statements are published -- the same direction of
-- dependency ADR-007 already has, and the same reason the
-- `statements_status_gate_trg` trigger exists.
--
-- It has NO contributor branch. Trust is not a parameter of this
-- function, because making it one would be the mechanism by which the
-- evidence bar got lowered (§8.4).
CREATE OR REPLACE FUNCTION public.recipe_auto_publish(p_recipe_id uuid)
RETURNS text
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = public, pg_temp
AS $fn$
DECLARE
  v_conf      jsonb;
  v_level     text;
  v_conds     jsonb;
  v_sources   jsonb;
  v_independent jsonb;
  v_switch    text;
  v_cap       integer;
  v_count     integer;
  v_service_account_id uuid;
  v_token     uuid;
  v_statement uuid;
  v_refused   text;
  r           record;
BEGIN
  -- (2) THE KILL SWITCH IS CHECKED FIRST -- before the recipe is
  --     touched (§7.1). A recipe mid-publish when the switch flips
  --     finishes; the switch prevents the NEXT one.
  SELECT auto_publish_mode, auto_publish_daily_cap
    INTO v_switch, v_cap
    FROM public.recipe_settings
   WHERE id = true;

  IF v_switch IS NULL THEN
    v_switch := 'disabled';
    v_cap := 20;
  END IF;

  IF v_switch = 'disabled' THEN
    RETURN format('REFUSED: the auto-publish switch is disabled (%s)', p_recipe_id);
  END IF;

  -- (1) THE CONDITIONS, evaluated against the rows.
  v_conf := public.recipe_compute_confidence(p_recipe_id);

  IF v_conf IS NULL THEN
    RETURN format('REFUSED: the recipe %s does not exist', p_recipe_id);
  END IF;

  v_level       := v_conf ->> 'level';
  v_conds       := v_conf -> 'conditions_met';
  v_sources     := v_conf -> 'sources';
  v_independent := v_conf -> 'independent_sources';

  IF v_level <> 'high' THEN
    -- The failing conditions are named, because that is what the owner
    -- reviews.
    --
    -- `jsonb_each` is a SET-RETURNING function, and it is used in the
    -- FROM of a subquery whose outer query aggregates -- so the
    -- aggregate is not nested inside another aggregate. (Writing
    -- `string_agg` directly over `jsonb_each` in the same SELECT is
    -- the "aggregate function calls cannot be nested" error.)
    SELECT string_agg(fmt, '; ')
      INTO v_refused
      FROM (
        SELECT key || ': ' || value ->> 'detail' AS fmt
          FROM jsonb_each(v_conds) AS e(key, value)
         WHERE (e.value ->> 'met')::boolean IS NOT TRUE
         ORDER BY e.key
      ) s;
    RETURN format('REFUSED: the recipe %s is %s, not high (%s)', p_recipe_id, v_level, v_refused);
  END IF;

  -- THE CAP (§7.2). It counts AUTO-PUBLISHED recipes only, per calendar
  -- day. Hitting the cap DEFERS the recipe -- it does not fail it.
  SELECT count(*) INTO v_count
    FROM public.recipe_publish_log
   WHERE publish_mode = 'auto'
     AND published_at >= date_trunc('day', now() AT TIME ZONE 'UTC') AT TIME ZONE 'UTC';

  IF v_count >= v_cap THEN
    RETURN format('REFUSED: the daily auto-publish cap (%s) is reached -- %s published today. The recipe is deferred, not failed.',
                  v_cap, v_count);
  END IF;

  -- The system actor must be live.
  SELECT id INTO v_service_account_id
    FROM public.service_accounts
   WHERE actor = 'system:auto-publish' AND revoked_at IS NULL;

  IF v_service_account_id IS NULL THEN
    RETURN format('REFUSED: the system actor system:auto-publish is revoked or unknown');
  END IF;

  -- (3) THE TRANSITION, through statement_set_status(), as the system
  --     actor.
  --
  -- THE TOKEN IS MINTED HERE, and only here. It is a row in a table
  -- the application role cannot write, generated inside this
  -- SECURITY DEFINER function, and it is DELETED when this function
  -- returns -- so it is single-use and cannot be replayed.
  --
  -- The token is bound to THIS recipe, so a token minted for one
  -- recipe cannot authorise a transition about another.
  --
  -- THE TOKEN IS PASSED AS THE "SESSION TOKEN". That is deliberate:
  -- `statement_set_status()` takes one text argument, and the system
  -- actor has no session -- so the argument that would normally carry
  -- a session carries the token instead. The branch recognises the
  -- token ONLY when the caller is also the function's owner, so the
  -- ordinary session path is untouched: a real session token is not a
  -- token in the table, and it never becomes one.
  INSERT INTO public.recipe_auto_publish_token (token, recipe_id, txid)
  VALUES (gen_random_uuid(), p_recipe_id, txid_current())
  RETURNING token INTO v_token;

  BEGIN
    -- The statements to publish: the recipe's own statements, i.e. the
    -- statements behind its sentences.
    FOR r IN
      SELECT DISTINCT rc.statement_id
        FROM public.recipe_sentences rs
        JOIN public.recipe_claims rc ON rc.recipe_sentence_id = rs.id
       WHERE rs.recipe_id = p_recipe_id
    LOOP
      v_statement := r.statement_id;
      PERFORM public.statement_set_status(v_statement, 'verified', v_token::text);
      PERFORM public.statement_set_status(v_statement, 'published', v_token::text);
    END LOOP;
  EXCEPTION
    WHEN OTHERS THEN
      -- Delete the token before the failure propagates, so a caller
      -- that catches the error cannot inherit a live token.
      DELETE FROM public.recipe_auto_publish_token WHERE token = v_token;
      RAISE;
  END;

  -- Delete the token on the success path too. It is single-use.
  DELETE FROM public.recipe_auto_publish_token WHERE token = v_token;

  -- (4) THE AUDIT TRAIL. There is no path by which a recipe becomes
  --     published without a row here (§2.5).
  INSERT INTO public.recipe_publish_log (
    recipe_id, confidence, publish_mode, conditions_met, sources, actor,
    service_account_id, kill_switch_on, daily_count_at_publish
  ) VALUES (
    p_recipe_id, v_level, 'auto', v_conds,
    jsonb_build_object('sources', v_sources, 'independent', v_independent),
    'system:auto-publish', v_service_account_id,
    (v_switch IN ('enabled','enabled_with_cap')),
    v_count + 1
  );

  -- The computed confidence is stored, so the UI and the publish path
  -- read the SAME number (§8.3).
  INSERT INTO public.recipe_confidence (
    recipe_id, level, conditions_met, independent_sources,
    source_count, ingredient_count, sentence_count, computed_at
  ) VALUES (
    p_recipe_id, v_level, v_conds, v_independent,
    (v_conf ->> 'source_count')::integer,
    (v_conf ->> 'ingredient_count')::integer,
    (v_conf ->> 'sentence_count')::integer,
    now()
  )
  ON CONFLICT (recipe_id) DO UPDATE
    SET level = EXCLUDED.level,
        conditions_met = EXCLUDED.conditions_met,
        independent_sources = EXCLUDED.independent_sources,
        source_count = EXCLUDED.source_count,
        ingredient_count = EXCLUDED.ingredient_count,
        sentence_count = EXCLUDED.sentence_count,
        computed_at = now();

  RETURN format('PUBLISHED: the recipe %s is %s', p_recipe_id, v_level);
END;
$fn$;

COMMENT ON FUNCTION public.recipe_auto_publish(uuid) IS
'The ONLY thing that may act as the system actor ''system:auto-publish''. '
'SECURITY DEFINER: inside it current_user is the owner, which is what '
'lets statement_set_status() recognise the caller as this function and '
'no other. It mints a single-use authorisation token in a table the '
'application role cannot write, re-checks EVERY HIGH condition from the '
'rows, checks the kill switch FIRST (before the recipe is touched) and '
'the daily cap, and only then performs the transition and writes '
'recipe_publish_log. It has NO contributor branch: trust is not a '
'parameter of it, because making it one would be the mechanism by which '
'the evidence bar got lowered (ADR-007-A1 §2.4.2, §8.4).';

-- The owner of the auto-publish function, as a function.
--
-- `current_user` inside a SECURITY DEFINER function is the OWNER. So
-- the branch in `statement_set_status()` can compare `current_user`
-- against the function's owner -- and a caller cannot be that owner
-- unless it IS the SECURITY DEFINER function.
--
-- It is defined AFTER `recipe_auto_publish()` on purpose: the body
-- resolves the regprocedure at creation time, so the function it names
-- must already exist.
CREATE OR REPLACE FUNCTION public.recipe_auto_publish_owner()
RETURNS text
LANGUAGE sql
STABLE
AS $$
  SELECT pg_get_userbyid(p.proowner)::text
    FROM pg_proc p
   WHERE p.oid = 'public.recipe_auto_publish(uuid)'::regprocedure;
$$;

COMMENT ON FUNCTION public.recipe_auto_publish_owner() IS
'The owner of recipe_auto_publish(). Inside a SECURITY DEFINER function '
'current_user IS the owner, so comparing current_user against this value '
'is what proves "the caller is recipe_auto_publish() itself" '
'(ADR-007-A1 §2.4.3).';

-- ITS GRANTS ARE NARROW, AND THAT MATTERS.
--
-- `EXECUTE` is revoked from PUBLIC -- which PostgreSQL grants by
-- default -- and granted only to the role that runs the auto-publish
-- job.
REVOKE ALL ON FUNCTION public.recipe_auto_publish(uuid) FROM PUBLIC;

-- The role that runs the auto-publish job. It is the migration role,
-- which is the role that owns the tables on live and in CI.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gustale_migrator') THEN
    EXECUTE 'GRANT EXECUTE ON FUNCTION public.recipe_auto_publish(uuid) TO gustale_migrator';
  END IF;
END;
$$;

-- ═══════════════════════════════════════════════════════════════════════
-- PART 11 -- THE PUBLISHABLE VIEW
-- ═══════════════════════════════════════════════════════════════════════

-- The publish gate, in one place (ADR-007).
--
-- The last clause is the important one: a recipe sentence with no
-- verified statement cannot be published.
CREATE OR REPLACE VIEW public.recipe_publishable AS
SELECT r.id
  FROM public.recipes r
  JOIN public.dishes d ON d.id = r.dish_id
 WHERE r.status = 'published'
   AND d.status = 'published'
   AND r.review_state = 'approved'
   AND EXISTS (SELECT 1 FROM public.recipe_ingredients ri
                JOIN public.ingredients i ON i.id = ri.ingredient_id
               WHERE ri.recipe_id = r.id AND i.status = 'published')
   AND EXISTS (SELECT 1 FROM public.recipe_sentences rs WHERE rs.recipe_id = r.id)
   AND NOT EXISTS (
         SELECT 1
           FROM public.recipe_sentences rs
           LEFT JOIN public.recipe_claims rc ON rc.recipe_sentence_id = rs.id
           LEFT JOIN public.statements st    ON st.id = rc.statement_id
          WHERE rs.recipe_id = r.id
            AND (st.id IS NULL
                 OR st.status NOT IN ('verified','published')));

COMMENT ON VIEW public.recipe_publishable IS
'The publish gate, in one place (ADR-007). A recipe sentence with no '
'verified statement cannot be published. The predicate keys on '
'statements.status IN (''verified'',''published''), which is exactly the '
'test the dish detail route uses, so a recipe and a dish cannot disagree '
'about what "evidenced" means. This is the POST-transition question; the '
'confidence computation asks the PRE-transition one (see '
'docs/MIGRATION-RECEIPT-0052.md §3).';

-- ═══════════════════════════════════════════════════════════════════════
-- THE PROOF
-- ═══════════════════════════════════════════════════════════════════════
--
-- The migration must be PROVEN, not merely applied:
--
--   1. every object it claims to create exists;
--   2. the system actor row exists and is a SYSTEM actor, with no
--      login, no email, no session and no credential;
--   3. the kill switch reads `disabled` and the cap reads 20;
--   4. a direct call to `statement_set_status()` with the system
--      actor is REFUSED -- the branch is not reachable from outside;
--   5. a FORGED token is REFUSED -- the token is the gate, and it is
--      not a string the caller chose;
--   6. the POSITIVE case: with the switch on and a HIGH recipe, the
--      auto-publish function really does publish -- so the proof is
--      not passing against a function that refuses everything;
--   7. a credential to the system actor is REFUSED by the amended 0048
--      guard;
--   8. a human account is still NOT recognised as a system actor, and
--      the bot rule still holds;
--   9. the application role has NO privilege on the token table;
--  10. the migration wrote NO recipe rows and NO statement rows --
--      the fixtures the proof made are removed again;
--  11. the confidence function runs and reports a level.
--
-- Every case asserts that a BAD thing is REFUSED -- so the proof must
-- also assert that a GOOD thing is ACCEPTED (case 6), or it would
-- pass against a function that refuses everything.
--
-- THE PROOF RUNS INSIDE THE TRANSACTION. A failure above rolls the
-- migration back, so the schema and its proof land together, or
-- neither lands. The fixtures the proof creates are DELETED before
-- the transaction commits, so the migration leaves NO content rows.
-- ═══════════════════════════════════════════════════════════════════════

DO $$
DECLARE
  v_service_count integer;
  v_cred_count integer;
  v_recipe_count integer;
  v_statement_count integer;
  v_level text;
  v_user_id text;
  v_settings record;
  v_token_count integer;
BEGIN
  -- (1) THE OBJECTS EXIST.
  IF to_regclass('public.recipes') IS NULL THEN
    RAISE EXCEPTION 'public.recipes does not exist';
  END IF;
  IF to_regclass('public.recipe_ingredients') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_ingredients does not exist';
  END IF;
  IF to_regclass('public.recipe_sentences') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_sentences does not exist';
  END IF;
  IF to_regclass('public.recipe_claims') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_claims does not exist';
  END IF;
  IF to_regclass('public.recipe_translations') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_translations does not exist';
  END IF;
  IF to_regclass('public.service_accounts') IS NULL THEN
    RAISE EXCEPTION 'public.service_accounts does not exist';
  END IF;
  IF to_regclass('public.recipe_settings') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_settings does not exist';
  END IF;
  IF to_regclass('public.recipe_confidence') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_confidence does not exist';
  END IF;
  IF to_regclass('public.recipe_publish_log') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_publish_log does not exist';
  END IF;
  IF to_regclass('public.recipe_auto_publish_token') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_auto_publish_token does not exist';
  END IF;
  IF to_regprocedure('public.recipe_auto_publish(uuid)') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_auto_publish(uuid) does not exist';
  END IF;
  IF to_regprocedure('public.recipe_compute_confidence(uuid)') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_compute_confidence(uuid) does not exist';
  END IF;
  IF to_regclass('public.recipe_publishable') IS NULL THEN
    RAISE EXCEPTION 'public.recipe_publishable does not exist';
  END IF;
  RAISE NOTICE 'CONFIRMED: every object the migration creates exists';

  -- (2) THE SYSTEM ACTOR, and its ABSENCES.
  SELECT count(*) INTO v_service_count
    FROM public.service_accounts
   WHERE actor = 'system:auto-publish' AND kind = 'system' AND revoked_at IS NULL;
  IF v_service_count <> 1 THEN
    RAISE EXCEPTION 'the system actor row is missing or duplicated (% rows)', v_service_count;
  END IF;

  -- It has NO login in "user".
  IF EXISTS (SELECT 1 FROM "user" u WHERE u.id = 'system:auto-publish') THEN
    RAISE EXCEPTION 'the system actor has a login in "user" -- it must not';
  END IF;

  -- It has NO publish credential.
  SELECT count(*) INTO v_cred_count
    FROM public.publish_credential WHERE actor = 'system:auto-publish';
  IF v_cred_count <> 0 THEN
    RAISE EXCEPTION 'the system actor holds % publish credential(s) -- it must hold none', v_cred_count;
  END IF;
  RAISE NOTICE 'CONFIRMED: the system actor is a row, with no login and no credential';

  -- The table can never hold a person.
  IF EXISTS (SELECT 1 FROM public.service_accounts WHERE kind <> 'system') THEN
    RAISE EXCEPTION 'a service_accounts row has a kind other than ''system''';
  END IF;

  -- (3) THE KILL SWITCH AND THE CAP.
  SELECT auto_publish_mode, auto_publish_enabled, auto_publish_daily_cap
    INTO v_settings FROM public.recipe_settings WHERE id = true;
  IF v_settings.auto_publish_mode <> 'disabled' THEN
    RAISE EXCEPTION 'the kill switch reads % -- it must ship disabled', v_settings.auto_publish_mode;
  END IF;
  IF v_settings.auto_publish_enabled THEN
    RAISE EXCEPTION 'the kill switch boolean reads true -- it must ship false';
  END IF;
  IF v_settings.auto_publish_daily_cap <> 20 THEN
    RAISE EXCEPTION 'the daily cap reads % -- it must be 20', v_settings.auto_publish_daily_cap;
  END IF;
  RAISE NOTICE 'CONFIRMED: the switch is disabled and the cap is 20';

  -- (4) A DIRECT CALL WITH THE SYSTEM ACTOR IS REFUSED.
  --
  -- This is the case that matters most. The branch in
  -- `statement_set_status()` must be reachable ONLY from
  -- `recipe_auto_publish()`. A direct call naming the system actor must
  -- be refused.
  BEGIN
    PERFORM public.statement_set_status(
      (SELECT id FROM public.statements LIMIT 1),
      'published',
      'system:auto-publish');
    RAISE EXCEPTION 'a direct statement_set_status() call with the system actor was ACCEPTED -- the branch is forgeable';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLERRM LIKE '%the branch is forgeable%' THEN
        RAISE;
      END IF;
      RAISE NOTICE 'CONFIRMED: a direct call with the system actor is refused: %',
        left(SQLERRM, 120);
  END;

  -- (5) A FORGED TOKEN IS REFUSED.
  --
  -- The token is the gate, so this is the case that proves it. A token
  -- is inserted DIRECTLY, with a value the caller chose -- exactly what
  -- an attacker with write access to the table would do -- and the
  -- call must still be refused.
  --
  -- The token is NOT bound to any recipe (the recipe does not exist
  -- yet at this point in the proof), so it fails the recipe binding as
  -- well as the caller check. The STRONGEST forgery -- a token that is
  -- valid in every respect except the caller -- is tested in the
  -- positive proof further down, once there is a recipe to bind to.
  BEGIN
    INSERT INTO public.recipe_auto_publish_token (token, recipe_id, txid)
    VALUES (gen_random_uuid(), NULL, txid_current());

    PERFORM public.statement_set_status(
      (SELECT id FROM public.statements LIMIT 1),
      'published',
      (SELECT token::text FROM public.recipe_auto_publish_token
        WHERE recipe_id IS NULL LIMIT 1));
    RAISE EXCEPTION 'a FORGED token produced an ACCEPTED transition -- the system-actor branch is forgeable';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLERRM LIKE '%the system-actor branch is forgeable%' THEN
        RAISE;
      END IF;
      -- If the call got PAST the authorisation, the failure would be
      -- about the content gate. It must not be.
      IF SQLERRM LIKE '%the gate for%' THEN
        RAISE EXCEPTION
          'a forged token got PAST the authorisation (the failure was the content gate, not the authorisation): %',
          left(SQLERRM, 160);
      END IF;
      RAISE NOTICE 'CONFIRMED: a forged token is refused: %', left(SQLERRM, 120);
  END;

  -- The forged token must not survive the proof.
  DELETE FROM public.recipe_auto_publish_token WHERE recipe_id IS NULL;

  -- (7) A CREDENTIAL TO THE SYSTEM ACTOR IS REFUSED.
  --
  -- The amended 0048 guard's new check. The insert is attempted and
  -- must be refused, and the refusal must name the SYSTEM ACTOR -- so
  -- the proof shows the new rule fired, not merely that some rule did.
  BEGIN
    INSERT INTO public.publish_credential (actor, credential_role)
      VALUES ('system:auto-publish', 'publisher');
    RAISE EXCEPTION 'a publish credential for the system actor was ACCEPTED -- the amended 0048 guard did not fire';
  EXCEPTION
    WHEN OTHERS THEN
      IF SQLERRM LIKE '%the amended 0048 guard did not fire%' THEN
        RAISE;
      END IF;
      IF SQLERRM NOT LIKE '%listed system actor%' THEN
        RAISE EXCEPTION
          'the credential for the system actor was refused, but NOT by the system-actor rule: %',
          left(SQLERRM, 160);
      END IF;
      RAISE NOTICE 'CONFIRMED: a credential for the system actor is refused by the system-actor rule';
  END;

  -- (8) A HUMAN ACCOUNT IS NOT A SYSTEM ACTOR, AND THE BOT RULE HOLDS.
  SELECT id INTO v_user_id FROM "user" LIMIT 1;
  IF v_user_id IS NOT NULL THEN
    IF EXISTS (SELECT 1 FROM public.service_accounts s
                WHERE s.actor = v_user_id AND s.revoked_at IS NULL) THEN
      RAISE EXCEPTION 'the account % is listed as a system actor -- it must not be', v_user_id;
    END IF;
    RAISE NOTICE 'CONFIRMED: a human account is not listed as a system actor';
  END IF;

  IF public.is_bot_publish_actor('system:auto-publish') THEN
    RAISE EXCEPTION 'the system actor was recognised as a bot -- the bot check is wrong';
  END IF;
  RAISE NOTICE 'CONFIRMED: the bot rule is unaffected by the system actor';

  -- (9) THE APPLICATION ROLE CANNOT WRITE THE TOKEN.
  --
  -- This is what makes the token unforgeable. If the application role
  -- could INSERT a token, the whole scheme would collapse.
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gustale') THEN
    IF has_table_privilege('gustale', 'public.recipe_auto_publish_token', 'INSERT') THEN
      RAISE EXCEPTION
        'the application role can INSERT into recipe_auto_publish_token -- the authorisation token is forgeable';
    END IF;
    RAISE NOTICE 'CONFIRMED: the application role has no privilege on the token table';
  END IF;

  -- (11) THE CONFIDENCE FUNCTION RUNS.
  --
  -- With no recipes, it reports `low` for a missing recipe -- and it
  -- reports it rather than raising.
  SELECT public.recipe_compute_confidence(gen_random_uuid()) ->> 'level' INTO v_level;
  IF v_level IS NULL THEN
    RAISE EXCEPTION 'recipe_compute_confidence() returned no level';
  END IF;
  RAISE NOTICE 'CONFIRMED: the confidence function runs and reports a level (%s)', v_level;

  -- The AUTO-PUBLISH FUNCTION REFUSES while the switch is disabled --
  -- and it refuses BEFORE touching the recipe.
  IF public.recipe_auto_publish(gen_random_uuid()) NOT LIKE 'REFUSED:%' THEN
    RAISE EXCEPTION 'recipe_auto_publish() did not refuse while the switch is disabled';
  END IF;
  RAISE NOTICE 'CONFIRMED: the auto-publish function refuses while the switch is disabled';
END;
$$;

-- ═══════════════════════════════════════════════════════════════════════
-- THE FORGE PROBE -- THE STRONGEST CASE
-- ═══════════════════════════════════════════════════════════════════════
--
-- The proof above proves that a direct call is refused. It does NOT
-- prove that the TOKEN is what refuses it -- a direct call is refused
-- because there is no session, whatever the token says.
--
-- So the probe IMPERSONATES the application role: it runs as a role
-- that is NOT the owner of `recipe_auto_publish()`, presents a token
-- of its own choosing, and calls `statement_set_status()` naming the
-- system actor. The call must be refused, and it must be refused by
-- the AUTHORISATION -- not by the content gate. If the error were
-- about the gate, the branch would have been reached and the proof
-- would have failed.
--
-- WHY THE PROBE IS RUN AS THE APPLICATION ROLE
-- --------------------------------------------
-- `SET LOCAL ROLE` is FORBIDDEN inside a SECURITY DEFINER function:
-- PostgreSQL raises "cannot set parameter role within security-
-- definer function". So a probe that wanted to drop to the
-- application role from inside a SECURITY DEFINER body cannot do it
-- with SET ROLE -- and a probe that ran as the OWNER would prove
-- nothing, because the owner check would pass.
--
-- The probe is therefore a plain `SECURITY INVOKER` function, and the
-- migration calls it from a `DO` block that has done `SET LOCAL ROLE
-- gustale`. Inside a DO block, `SET LOCAL ROLE` IS allowed (it is
-- forbidden only inside a SECURITY DEFINER body), and the block runs
-- as the application role for the duration of the call.
--
-- The token the probe presents is MINTED BY THE OWNER on the probe's
-- behalf, through a SECURITY DEFINER helper. That is the strongest
-- forgery there is: the token table's OWNER writes a token for a
-- caller that is not the owner. It still must not work, because the
-- `current_user` check fails.
-- ═══════════════════════════════════════════════════════════════════════

CREATE OR REPLACE FUNCTION public.recipe_system_actor_forge_probe(p_token text)
RETURNS text
LANGUAGE plpgsql
AS $probe$
DECLARE
  v_err text;
  v_role text;
BEGIN
  -- The role the probe runs as. It must NOT be the owner of
  -- `recipe_auto_publish()`, or the owner check would pass and the
  -- probe would prove nothing.
  v_role := current_user;

  IF v_role = public.recipe_auto_publish_owner() THEN
    RETURN format('SKIPPED: the probe ran as the owner (%s), so it would prove nothing', v_role);
  END IF;

  -- The token the probe presents was minted by the OWNER, in THIS
  -- transaction, for THIS recipe -- so it is valid in every respect
  -- except the one that matters: the caller is not the owner.
  BEGIN
    PERFORM public.statement_set_status(
      (SELECT id FROM public.statements
        WHERE subject_type = 'recipe'
        LIMIT 1),
      'published',
      p_token);
    v_err := NULL;
  EXCEPTION
    WHEN OTHERS THEN
      v_err := SQLERRM;
  END;

  IF v_err IS NULL THEN
    RAISE EXCEPTION 'a forged token produced an ACCEPTED transition -- the system-actor branch is forgeable';
  END IF;

  -- If the call got past authorisation, the failure would be about the
  -- content gate. It must not be.
  IF v_err LIKE '%the gate for%' THEN
    RAISE EXCEPTION
      'a forged token got past authorisation (the failure was the content gate, not the authorisation): %',
      left(v_err, 160);
  END IF;

  RETURN format('a forged token is refused as %s: %s', v_role, left(v_err, 120));
END;
$probe$;

COMMENT ON FUNCTION public.recipe_system_actor_forge_probe(text) IS
'The forge test for the system-actor branch of statement_set_status(). It '
'presents an authorisation token that is valid in EVERY respect -- it '
'exists, it was minted in this transaction, it names the right recipe, and '
'it was minted by the token table''s owner -- and proves the call is still '
'refused, because the current_user check must ALSO hold. It is SECURITY '
'INVOKER so that it runs as whichever role called it; the migration calls '
'it after SET LOCAL ROLE, so it runs as the application role rather than '
'as the owner. A refusal whose message is about the content GATE would '
'mean the branch had been reached, and this function FAILS in that case '
'rather than reporting success.';

-- ═══════════════════════════════════════════════════════════════════════
-- THE POSITIVE PROOF -- THE FUNCTION REALLY PUBLISHES
-- ═══════════════════════════════════════════════════════════════════════
--
-- Everything above proves that BAD things are refused. On its own that
-- is not enough: a function that refused EVERYTHING would pass all of
-- it.
--
-- So this builds a real recipe -- a published dish, published
-- ingredients, two independent S1-S5 sources with locators, and a
-- sentence whose claim has a statement -- turns the kill switch ON,
-- and calls `recipe_auto_publish()`. It must:
--
--   * report the recipe as HIGH;
--   * actually publish the statement (status -> published);
--   * record the transition in `statement_status_log` with the actor
--     `system:auto-publish`;
--   * write a row in `recipe_publish_log` carrying the
--     `service_account_id`;
--   * leave NO authorisation token behind -- the token is single-use.
--
-- The fixtures are created and removed inside the migration's
-- transaction, so nothing they created survives the commit.
--
-- THE SOURCES ARE S2 AND S3 -- TWO INDEPENDENT CLASSES. Two citations
-- from ONE source would be one source, not two, so the independence
-- condition (6) would fail and the recipe would be MEDIUM. That is the
-- point of the condition, and the fixture honours it.
DO $$
DECLARE
  v_dish        uuid;
  v_ingredient  uuid;
  v_predicate   uuid;
  v_source_a    uuid;
  v_source_b    uuid;
  v_recipe      uuid;
  v_sentence    uuid;
  v_statement   uuid;
  v_result      text;
  v_status      text;
  v_actor       text;
  v_log_count   integer;
  v_pub_count   integer;
  v_token_count integer;
  v_conf        jsonb;
  v_forged      uuid;
  v_probe       text;
BEGIN
  -- THE FIXTURES. A published dish and a published ingredient.
  SELECT id INTO v_dish FROM public.dishes WHERE status = 'published' LIMIT 1;
  IF v_dish IS NULL THEN
    RAISE EXCEPTION 'the fixture needs a published dish -- there is none';
  END IF;
  SELECT id INTO v_ingredient FROM public.ingredients WHERE status = 'published' LIMIT 1;
  IF v_ingredient IS NULL THEN
    RAISE EXCEPTION 'the fixture needs a published ingredient -- there is none';
  END IF;
  SELECT id INTO v_predicate FROM public.predicates LIMIT 1;

  -- TWO INDEPENDENT SOURCES, in different classes, each with a locator.
  INSERT INTO public.sources (id, source_type, title, source_class, language)
  VALUES ('f0000000-0000-0000-0000-0000000000a1', 'book', 'the recipe proof source A', 'S2', 'en')
  ON CONFLICT (id) DO NOTHING;
  INSERT INTO public.sources (id, source_type, title, source_class, language)
  VALUES ('f0000000-0000-0000-0000-0000000000b2', 'book', 'the recipe proof source B', 'S3', 'en')
  ON CONFLICT (id) DO NOTHING;
  v_source_a := 'f0000000-0000-0000-0000-0000000000a1';
  v_source_b := 'f0000000-0000-0000-0000-0000000000b2';

  -- THE RECIPE.
  INSERT INTO public.recipes (id, dish_id, slug, title, servings, status, review_state)
  VALUES ('e0000000-0000-0000-0000-000000000001', v_dish,
          'the-recipe-proof-fixture', 'the recipe proof fixture',
          4, 'draft', 'approved')
  RETURNING id INTO v_recipe;

  INSERT INTO public.recipe_ingredients (recipe_id, ingredient_id, quantity, unit, position)
  VALUES (v_recipe, v_ingredient, '2', 'cups', 1);

  -- THE SENTENCE, and the STATEMENT that backs it.
  INSERT INTO public.recipe_sentences (id, recipe_id, field, locale, position, text, is_original)
  VALUES ('e0000000-0000-0000-0000-000000000002', v_recipe, 'step', 'en', 1,
          'the proof sentence', true)
  RETURNING id INTO v_sentence;

  INSERT INTO public.statements (
    id, subject_type, subject_id, predicate_id, value_type, value_literal,
    value_literal_type, claim_class, status, independence
  ) VALUES (
    'e0000000-0000-0000-0000-000000000003', 'recipe', v_recipe, v_predicate,
    'literal', 'a proof value', 'text', 'documented', 'research_pending', 'single'
  )
  RETURNING id INTO v_statement;

  INSERT INTO public.recipe_claims (recipe_sentence_id, statement_id)
  VALUES (v_sentence, v_statement);

  -- THE TWO CITATIONS, each with a locator -- condition 7' requires
  -- an exact locator on every core claim.
  --
  -- `retrieved_at` is NOT NULL with no default, so it is set
  -- explicitly.
  INSERT INTO public.claim_citations (statement_id, source_id, stance, locator, retrieved_at)
  VALUES (v_statement, v_source_a, 'supports', 'chapter 2, page 41', now());
  INSERT INTO public.claim_citations (statement_id, source_id, stance, locator, retrieved_at)
  VALUES (v_statement, v_source_b, 'supports', 'chapter 5, page 118', now());

  -- THE CONFIDENCE MUST BE HIGH, or the fixture is wrong.
  v_conf := public.recipe_compute_confidence(v_recipe);
  IF v_conf ->> 'level' <> 'high' THEN
    RAISE EXCEPTION
      'the proof fixture computed % and not high -- the conditions are: %',
      v_conf ->> 'level', v_conf -> 'conditions_met';
  END IF;
  RAISE NOTICE 'CONFIRMED: the proof fixture is HIGH (%s S1-S5 sources, %s independent)',
    v_conf ->> 'source_count',
    jsonb_array_length(v_conf -> 'independent_sources');

  -- THE SWITCH IS TURNED ON for the duration of this proof. It is
  -- turned off again, and the migration leaves it `disabled` -- which
  -- is what case (3) above asserts.
  UPDATE public.recipe_settings
     SET auto_publish_mode = 'enabled'
   WHERE id = true;

  -- THE CALL.
  v_result := public.recipe_auto_publish(v_recipe);

  IF v_result NOT LIKE 'PUBLISHED:%' THEN
    RAISE EXCEPTION 'recipe_auto_publish() did not publish the HIGH fixture: %', v_result;
  END IF;
  RAISE NOTICE 'CONFIRMED: recipe_auto_publish() published the HIGH fixture';

  -- THE STATEMENT really moved.
  SELECT status INTO v_status FROM public.statements WHERE id = v_statement;
  IF v_status <> 'published' THEN
    RAISE EXCEPTION 'the fixture statement is % and not published', v_status;
  END IF;
  RAISE NOTICE 'CONFIRMED: the fixture statement is published';

  -- THE AUDIT TRAIL names the system actor.
  SELECT actor INTO v_actor
    FROM public.statement_status_log
   WHERE statement_id = v_statement AND to_status = 'published'
   ORDER BY created_at DESC LIMIT 1;
  IF v_actor IS DISTINCT FROM 'system:auto-publish' THEN
    RAISE EXCEPTION 'the transition log names % and not system:auto-publish', v_actor;
  END IF;
  RAISE NOTICE 'CONFIRMED: the transition is logged as the system actor';

  -- THE PUBLISH LOG has a row, with the service_account_id.
  SELECT count(*) INTO v_pub_count
    FROM public.recipe_publish_log
   WHERE recipe_id = v_recipe AND publish_mode = 'auto' AND actor = 'system:auto-publish';
  IF v_pub_count <> 1 THEN
    RAISE EXCEPTION 'the publish log holds % rows for the fixture -- it must hold 1', v_pub_count;
  END IF;
  IF NOT EXISTS (
    SELECT 1 FROM public.recipe_publish_log
     WHERE recipe_id = v_recipe AND service_account_id IS NOT NULL
  ) THEN
    RAISE EXCEPTION 'the publish log row carries no service_account_id';
  END IF;
  RAISE NOTICE 'CONFIRMED: the publish log holds the audit row';

  -- THE TOKEN IS SINGLE-USE: none may survive the call.
  SELECT count(*) INTO v_token_count FROM public.recipe_auto_publish_token;
  IF v_token_count <> 0 THEN
    RAISE EXCEPTION 'the call left % authorisation token(s) behind -- the token must be single-use', v_token_count;
  END IF;
  RAISE NOTICE 'CONFIRMED: the authorisation token is single-use';

  -- ═══════════════════════════════════════════════════════════════════
  -- THE FORGE TEST -- THE STRONGEST CASE
  -- ═══════════════════════════════════════════════════════════════════
  --
  -- Everything above proves that BAD things are refused. It does NOT
  -- prove that the TOKEN is what refuses them -- a direct call is
  -- refused because there is no session, whatever the token says.
  --
  -- So this is the strongest forgery there is. The OWNER mints a token
  -- that is VALID IN EVERY RESPECT:
  --
  --   * it exists in the token table;
  --   * it was minted in THIS transaction, so the txid matches;
  --   * it is bound to THIS recipe, so it names the right recipe;
  --   * and it was minted by the table's owner, so it is exactly what
  --     the legitimate caller would present.
  --
  -- The ONLY thing wrong with it is WHO IS CALLING. The probe runs as
  -- the application role -- the role an attacker would be -- and it
  -- must be refused. If the call got past the authorisation, the
  -- failure would be about the CONTENT GATE, and this block would fail
  -- rather than pass.
  --
  -- So this proves the ADR's requirement exactly: the token AND
  -- `current_user` are checked together, and the `current_user` half
  -- is what stops a token that is otherwise perfect.
  --
  -- WHY THE PROBE RUNS AS THE APPLICATION ROLE
  -- ------------------------------------------
  -- `SET LOCAL ROLE` is FORBIDDEN inside a SECURITY DEFINER function:
  -- PostgreSQL raises "cannot set parameter role within security-
  -- definer function". A probe that ran as the OWNER would prove
  -- nothing, because the owner check would pass.
  --
  -- The probe is therefore a plain `SECURITY INVOKER` function, and
  -- this block calls it after `SET LOCAL ROLE gustale`. Inside a DO
  -- block `SET LOCAL ROLE` IS allowed -- it is forbidden only inside a
  -- SECURITY DEFINER body.
  INSERT INTO public.recipe_auto_publish_token (token, recipe_id, txid)
  VALUES (gen_random_uuid(), v_recipe, txid_current())
  RETURNING token INTO v_forged;

  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'gustale') THEN
    EXECUTE 'SET LOCAL ROLE gustale';
    v_probe := public.recipe_system_actor_forge_probe(v_forged::text);
    EXECUTE 'RESET ROLE';
  ELSE
    v_probe := public.recipe_system_actor_forge_probe(v_forged::text);
  END IF;

  IF v_probe NOT LIKE 'SKIPPED:%' THEN
    RAISE NOTICE 'CONFIRMED: %', v_probe;
  ELSE
    -- The probe could not run as a non-owner role. That is a WEAKER
    -- proof, so it is said out loud rather than passed over.
    RAISE NOTICE 'NOTE: %', v_probe;
  END IF;

  -- The forged token must not survive the proof.
  DELETE FROM public.recipe_auto_publish_token WHERE token = v_forged;

  -- THE SWITCH GOES BACK OFF, and the fixtures go away.
  UPDATE public.recipe_settings
     SET auto_publish_mode = 'disabled'
   WHERE id = true;

  -- THE FIXTURES GO AWAY.
  --
  -- THE ORDER MATTERS, TWICE OVER:
  --
  -- 1. `statements.subject_id` references the recipe when
  --    `subject_type = 'recipe'`, so the statement must go BEFORE the
  --    recipe. Deleting the recipe first raises "no recipe with id
  --    ...".
  --
  -- 2. `statements_subject_exists_trg` is a DEFERRABLE CONSTRAINT
  --    TRIGGER -- it fires at COMMIT, not at the delete. So if the
  --    recipe is deleted in the same transaction, the deferred check
  --    runs at COMMIT, finds no recipe, and the whole transaction
  --    fails with "no recipe with id ...".
  --
  -- `SET CONSTRAINTS ALL IMMEDIATE` resolves (2): it fires the
  -- deferred constraint check NOW, while the recipe still exists, so
  -- the check passes on the row as it stands. After that the recipe
  -- can be deleted safely, and there is no deferred check left
  -- pending for the commit.
  --
  -- It is issued inside a DO block, because `SET CONSTRAINTS` is a
  -- transaction-control command and plpgsql requires such commands to
  -- be run with EXECUTE.
  --
  -- NB: the inner block uses its own dollar-quote tag, not the plain
  -- two-dollar form. A nested plain two-dollar tag would TERMINATE
  -- the enclosing block -- the outer DO would end at the inner one,
  -- and the rest of the outer block would be parsed as top-level SQL.
  -- For the same reason, the comment above must not contain the
  -- plain two-dollar form either: a dollar-quote is closed by the
  -- FIRST matching tag, even inside a comment.
  DO $inner$
  BEGIN
    EXECUTE 'SET CONSTRAINTS ALL IMMEDIATE';
  END;
  $inner$;

  DELETE FROM public.recipe_publish_log WHERE recipe_id = v_recipe;
  DELETE FROM public.recipe_confidence WHERE recipe_id = v_recipe;
  DELETE FROM public.recipe_claims WHERE statement_id = v_statement;
  DELETE FROM public.recipe_sentences WHERE recipe_id = v_recipe;
  DELETE FROM public.claim_citations WHERE statement_id = v_statement;
  DELETE FROM public.statement_status_log WHERE statement_id = v_statement;
  DELETE FROM public.statements WHERE id = v_statement;
  DELETE FROM public.recipe_ingredients WHERE recipe_id = v_recipe;
  DELETE FROM public.recipes WHERE id = v_recipe;
  DELETE FROM public.sources WHERE id IN (v_source_a, v_source_b);
END;
$$;

-- ═══════════════════════════════════════════════════════════════════════
-- THE MIGRATION LEFT NO CONTENT ROWS
-- ═══════════════════════════════════════════════════════════════════════
--
-- The proof above created fixtures and removed them again. This block
-- asserts the end state, so a fixture that survived the cleanup is
-- caught here rather than on live.
DO $$
DECLARE
  v_recipe_count integer;
  v_statement_count integer;
  v_token_count integer;
BEGIN
  SELECT count(*) INTO v_recipe_count FROM public.recipes;
  IF v_recipe_count <> 0 THEN
    RAISE EXCEPTION 'the migration left % recipe rows behind -- it must leave none', v_recipe_count;
  END IF;

  SELECT count(*) INTO v_statement_count
    FROM public.statements WHERE subject_type = 'recipe';
  IF v_statement_count <> 0 THEN
    RAISE EXCEPTION 'the migration left % recipe statements behind -- it must leave none', v_statement_count;
  END IF;

  SELECT count(*) INTO v_token_count FROM public.recipe_auto_publish_token;
  IF v_token_count <> 0 THEN
    RAISE EXCEPTION 'the migration left % authorisation token(s) behind -- it must leave none', v_token_count;
  END IF;

  -- The kill switch is OFF, as it shipped.
  IF (SELECT auto_publish_mode FROM public.recipe_settings WHERE id = true) <> 'disabled' THEN
    RAISE EXCEPTION 'the kill switch is not disabled at the end of the migration';
  END IF;

  RAISE NOTICE 'CONFIRMED: the migration left no content rows, no token, and the switch is off';
END;
$$;

DO $$
BEGIN
  RAISE NOTICE 'RECIPES_SCHEMA_OK=1';
END;
$$;

-- The proof ran INSIDE the transaction. A failure above would have
-- rolled the migration back, which is the point: the schema and its
-- proof land together, or neither lands.
COMMIT;
