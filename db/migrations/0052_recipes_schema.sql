'docs/MIGRATION-RECEIPT-0052.md §3 records the deviation.';

-- ═══════════════════════════════════════════════════════════════════════
-- PART 8 -- THE AMENDED 0048 GUARD, AND THE SYSTEM-ACTOR BRANCH
-- ═══════════════════════════════════════════════════════════════════════

-- 0048's guard gains a check: a credential is refused to ANY listed
-- system actor (ADR-007-A1 §2.4.3).
--
-- 0048's original three checks are UNCHANGED. The amendment ADDS a
-- rule; it relaxes nothing.
--
-- THE SYSTEM-ACTOR CHECK RUNS FIRST, and that ordering is deliberate.
--
-- The system actor has NO login in "user", so 0048's FIRST check --
-- "the account must exist in \"user\"" -- would already refuse it. If
-- that check ran first, the system-actor rule would be UNREACHABLE:
-- every attempt would be refused by the login check, the rule would
-- never fire, and the proof could not tell the two refusals apart.
--
-- So the system-actor check runs FIRST, and the login check follows.
-- The refusal then names the system actor, which is the more useful
-- message and the one ADR-007-A1 §2.4.3 specifies.
CREATE OR REPLACE FUNCTION public.publish_credential_owner_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $guard$
DECLARE
  v_may_issue boolean := false;
BEGIN
  -- (1) THE ACTOR MUST NOT BE A LISTED SYSTEM ACTOR. (ADR-007-A1 §2.4.3.)
  --
  -- A system actor is not a login and holds no credential. It publishes
  -- only through the SECURITY DEFINER function that owns it, which
  -- re-checks every condition itself. A credential would give it a
  -- second, far weaker route to publishing -- and would make it a thing
  -- that can be issued, copied, rotated and leaked.
  IF EXISTS (SELECT 1 FROM public.service_accounts s
              WHERE s.actor = NEW.actor AND s.revoked_at IS NULL) THEN
    RAISE EXCEPTION
      'the publish credential for % is refused: it is a listed system actor. '
      'A system actor publishes only through recipe_auto_publish().',
      NEW.actor;
  END IF;

  -- (2) The account must exist -- in the LOGIN table. (0048's rule, unchanged.)
  IF NOT EXISTS (SELECT 1 FROM "user" u WHERE u.id = NEW.actor) THEN
    RAISE EXCEPTION
      'the publish credential for % is refused: there is no such account in "user"',
      NEW.actor;
  END IF;

  -- (3) THE ACTOR MUST NOT BE A BOT. (0048's rule, unchanged.)
  IF public.is_bot_publish_actor(NEW.actor) THEN
    RAISE EXCEPTION
      'the publish credential for % is refused: a bot account must never hold a publish credential',
      NEW.actor;
  END IF;

  -- (4) THE WRITER must be a MEMBER OF THE ISSUER ROLE. (0048's rule, unchanged.)
  SELECT pg_has_role(current_user, 'gustale_credential_issuer', 'MEMBER')
    INTO v_may_issue;

  IF NOT v_may_issue THEN
    RAISE EXCEPTION
      'the publish credential for % is refused: the writer % is not a member of the issuer role',
      NEW.actor, current_user;
  END IF;

  RETURN NEW;
END;
$guard$;

COMMENT ON FUNCTION public.publish_credential_owner_guard() IS
'Refuses a publish credential to ANY listed system actor (ADR-007-A1 '
'§2.4.3), to an actor with no login in Better Auth''s "user" table, to a '
'BOT account, and to a writer that is not a member of '
'gustale_credential_issuer. The last three are 0048''s rules, unchanged. '
'The system-actor check runs FIRST so that it is reachable: the system '
'actor has no login, so the login check would otherwise refuse it and the '
'rule would never fire. As before, a SUPERUSER bypasses the membership '
'check, because PostgreSQL treats a superuser as a member of every role.';

-- The widened `statements.subject_type` CHECK, so a statement may carry
-- a recipe subject (§8.2).
--
-- The CHECK is dropped and re-added, because a CHECK cannot be altered
-- in place. The widening is ADDITIVE: 'recipe' is added to the existing
-- 'dish' and 'place'.
ALTER TABLE public.statements
  DROP CONSTRAINT IF EXISTS statements_subject_type_check;
ALTER TABLE public.statements
  ADD CONSTRAINT statements_subject_type_check
  CHECK (subject_type IN ('dish','place','recipe'));

COMMENT ON CONSTRAINT statements_subject_type_check ON public.statements IS
'The subject types a statement may carry. ''recipe'' was added by ADR-007-A1 '
'§8.2 so a recipe''s sentences can carry statements. The widening is '
'ADDITIVE: ''dish'' and ''place'' are unchanged.';

-- The subject-existence trigger must know about the new type, or a
-- statement with a recipe subject would be refused.
CREATE OR REPLACE FUNCTION public.statements_check_subject()
RETURNS trigger
LANGUAGE plpgsql
AS $function$
BEGIN
  IF NEW.subject_type = 'dish' THEN
    IF NOT EXISTS (SELECT 1 FROM dishes d WHERE d.id = NEW.subject_id) THEN
      RAISE EXCEPTION 'statement %: no dish with id %', NEW.id, NEW.subject_id;
    END IF;
  ELSIF NEW.subject_type = 'place' THEN
    IF NOT EXISTS (SELECT 1 FROM geo_entities g WHERE g.id = NEW.subject_id) THEN
      RAISE EXCEPTION 'statement %: no place with id %', NEW.id, NEW.subject_id;
    END IF;
  ELSIF NEW.subject_type = 'recipe' THEN
    IF NOT EXISTS (SELECT 1 FROM recipes r WHERE r.id = NEW.subject_id) THEN
      RAISE EXCEPTION 'statement %: no recipe with id %', NEW.id, NEW.subject_id;
    END IF;
  ELSE
    RAISE EXCEPTION 'statement %: unknown subject_type %', NEW.id, NEW.subject_type;
  END IF;
  RETURN NEW;
END;
$function$;

