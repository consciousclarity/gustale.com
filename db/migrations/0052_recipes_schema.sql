-- 0052_recipes_schema.sql
--
-- ITEM 2 OF THE RECIPES TASK: the schema the recipes property needs.
--
-- WHAT THIS MIGRATION IS
-- ---------------------
-- ADR-007 (`docs/ADR-007-recipe-schema.md`) accepted the five recipes
-- tables. ADR-007-A1 (`docs/ADR-007-A1-recipes-confidence-autopublish-
-- contributors-language-urls.md`) amended that shape with the owner's
-- five decisions of 2026-11-08, and §8 of that amendment is the
-- authoritative schema for this migration.
--
-- So this migration creates:
--
--   * `recipes`, `recipe_ingredients`, `recipe_sentences`,
--     `recipe_claims`, `recipe_translations` -- ADR-007's five tables,
--     with ADR-007-A1's language-first amendments to the two that carry
--     text (§4.3);
--   * `service_accounts` -- the system actors, and the ONE row
--     `system:auto-publish` (§2.4);
--   * `recipe_settings` -- the kill switch and the daily cap (§7.1,
--     §7.2);
--   * `recipe_confidence` -- the computed confidence and its evidence
--     (§8.1);
--   * `recipe_publish_log` -- the audit trail; no recipe becomes
--     published without a row here (§2.5);
--   * `recipe_auto_publish()` -- the SECURITY DEFINER function that is
--     the ONLY thing that may act as the system actor (§2.4.2, §8.4);
--   * `recipe_auto_publish_token` -- the authorisation token that
--     proves the caller of `statement_set_status()` IS
--     `recipe_auto_publish()` (§2.4.3, §8.4);
--   * the widened `statements.subject_type` CHECK, so a statement may
--     carry a recipe subject (§8.2);
--   * the amended 0048 credential guard -- it now refuses a credential
--     to ANY listed system actor (§2.4.3);
--   * the `statement_set_status()` branch that accepts the system actor
--     on EXACTLY ONE path (§2.4.3);
--   * the trigger that refuses a slug change on a published ingredient
--     (§3.4).
--
-- WHAT IT DOES NOT DO
-- -------------------
-- It writes NO recipe rows, NO ingredient rows and NO statement rows.
-- It creates the schema, and it PROVES the schema -- the proof runs
-- inside the migration's transaction, so a failed proof rolls the
-- whole migration back.
--
-- THE AUTHORISATION DESIGN -- AND WHY IT IS THIS WAY
-- ---------------------------------------------------
-- §8.4 is explicit about the one thing that must not be got wrong:
--
--   "The function sets a transaction-local marker that only a
--    SECURITY DEFINER function of the migration's ownership can set,
--    and statement_set_status() checks that marker before honouring
--    the system actor. ... set_config on a custom GUC can be called by
--    any role, so the marker is NOT a plain GUC -- it is checked
--    against current_user AND the marker together, and the branch
--    additionally requires that the caller is the function's owner."
--
-- A PLAIN GUC DOES NOT SATISFY THIS. `set_config('gustale.x', 'on',
-- true)` can be called by ANY role, so a GUC marker is a string the
-- attacker chooses. The nonce that an earlier draft paired with it was
-- equally decorative: the nonce was also a GUC, so the attacker chose
-- the nonce too. Checking a caller-chosen nonce against a
-- caller-chosen marker proves nothing.
--
-- What IS unforgeable in PostgreSQL is a TOKEN STORED IN A TABLE that
-- the attacker cannot write. So the token is:
--
--   1. generated inside `recipe_auto_publish()` (SECURITY DEFINER),
--      from `gen_random_uuid()`, and never leaves the database;
--   2. stored in `recipe_auto_publish_token`, a table the application
--      role has NO privilege on;
--   3. compared inside `statement_set_status()` against the token
--      that is LIVE AT THAT MOMENT -- and it is DELETED the moment the
--      function returns, so it is single-use and cannot be replayed.
--
-- So the branch requires THREE independent facts to hold at once, and
-- an attacker must forge all three:
--
--   a. the token row exists and matches (it is in a table the
--      attacker cannot write);
--   b. the caller is the owner of `recipe_auto_publish()` -- proven by
--      `current_user`, which inside a SECURITY DEFINER function IS the
--      owner, and which no other role can be;
--   c. the token was generated by THIS call -- proven by the token
--      being deleted on the way out, and by the fact that the attacker
--      cannot insert a token row.
--
-- (a) and (c) are the table; (b) is the `current_user` check. The
-- ADR asks for exactly this pair: `current_user` AND the marker.
--
-- WHY NOT A GUC AT ALL
-- --------------------
-- Because the GUC would have to be trusted, and it cannot be. The
-- token table is trusted: it is owned by the migration role, the
-- application role has no privilege on it, and the ONLY code that
-- writes it is the SECURITY DEFINER function itself. A GUC is written
-- by whoever calls `set_config`, and that includes the attacker.
--
-- WHY `statement_set_status()` CAN READ THE TOKEN
-- ----------------------------------------------
-- It is SECURITY INVOKER (0047 left it that way, and 0042's comment
-- depends on it: "it is not SECURITY DEFINER"). So it reads the
-- token table under the CALLER's privileges -- and the caller is
-- `recipe_auto_publish()` running as its owner, which is the role
-- that owns the table. That is exactly why the check works: the read
-- succeeds for the legitimate caller and FAILS with "permission
-- denied" for anyone else, which is itself the second half of the
-- authorisation.
--
-- So the token read is not a `SECURITY DEFINER` helper -- it is the
-- caller's own privileges, and the table's grants are the check.
--
-- THE PROOF EXERCISES THE FORGERY
-- -------------------------------
-- The migration's proof must show that a direct call to
-- `statement_set_status()` naming the system actor is REFUSED, and
-- that a call with the marker FORGED BY HAND is refused too. The
-- second case is the one that proves the token is the gate. It is run
-- through a `SECURITY DEFINER` probe owned by the migration role and
-- the probe is granted the ability to impersonate the application
-- role (`SET ROLE` is FORBIDDEN inside a SECURITY DEFINER function --
-- PostgreSQL raises "cannot set parameter role within security-
-- definer function" -- so the probe cannot drop its own privileges
-- that way). The probe therefore proves the branch is unreachable
-- from outside, and it says so out loud if it could not run.
--
-- THE CONDITION-4 CIRCULARITY
-- --------------------------
-- §8.3's condition 4 requires "every sentence has a claim with a
-- statement at status IN ('verified','published')". §8.4's function
-- transitions those statements TO verified/published. Read literally,
-- the recipe can only be HIGH once it is already published -- which
-- would make the auto-publish function dead code.
--
-- The reading this migration implements, and states plainly, is:
-- condition 4 is checked against the statements' EVIDENCE, not
-- against their CURRENT STATUS -- that is, every sentence's claim
-- must have a statement that is EVIDENCED (it has the supporting
-- S1-S5 citations the other conditions require), and the function is
-- what LIFTS those statements to verified/published. In other words,
-- condition 4 asks "is this sentence backed by an evidenced claim?",
-- and the transition is the CONSEQUENCE of that, not its precondition.
--
-- This is the only reading under which §8.4's function can ever
-- succeed, and it is consistent with ADR-007's own rule that "a
-- recipe sentence with no verified statement cannot be published" --
-- that view still keys on the POST-transition status, so a recipe is
-- only publishable once the statements really are verified. The
-- confidence computation asks the pre-transition question; the
-- publish view asks the post-transition one. Neither contradicts
-- the other.
--
-- The ADR's own wording is ambiguous here, so this is recorded as a
-- DEVIATION for the owner to confirm: `docs/MIGRATION-RECEIPT-0052.md`
-- §3 spells it out. It does not weaken the evidence bar -- the
-- function still re-checks EVERY condition from the rows, including
-- the S1-S5 class, the independence count and the locator.

BEGIN;

-- ═══════════════════════════════════════════════════════════════════════
-- PART 1 -- ADR-007's FIVE TABLES
-- ═══════════════════════════════════════════════════════════════════════

-- The recipe.
CREATE TABLE IF NOT EXISTS public.recipes (
  id                  uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  dish_id             uuid NOT NULL REFERENCES public.dishes(id) ON DELETE CASCADE,
  slug                text NOT NULL UNIQUE,
  title               text NOT NULL,
  content_type        text NOT NULL DEFAULT 'recipe'
                        CHECK (content_type IN ('recipe','variation','technique','base','template')),
  servings            integer,
  prep_minutes        integer,
  cook_minutes        integer,
  difficulty          integer,
  status              text NOT NULL DEFAULT 'draft'
                        CHECK (status IN ('draft','published','archived')),
  review_state        text NOT NULL DEFAULT 'unreviewed'
                        CHECK (review_state IN ('unreviewed','in_review','approved','rejected')),
  created_by          text,
  last_edited_by      text,
  created_at          timestamptz NOT NULL DEFAULT now(),
  updated_at          timestamptz NOT NULL DEFAULT now(),
  is_primary          boolean NOT NULL DEFAULT false
);

COMMENT ON TABLE public.recipes IS
'The recipe. ADR-007 accepted this shape; ADR-007-A1 §8.1 keeps it. The '
'confidence is NOT a column here -- it is COMPUTED and lives in '
'recipe_confidence, because a column would invite it to be set by hand.';

-- One row per ingredient line, with its amount.
CREATE TABLE IF NOT EXISTS public.recipe_ingredients (
  id               uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  recipe_id        uuid NOT NULL REFERENCES public.recipes(id) ON DELETE CASCADE,
  ingredient_id    uuid NOT NULL REFERENCES public.ingredients(id),
  quantity         text,
  unit             text,
  is_optional      boolean NOT NULL DEFAULT false,
  preparation_note text,
  position         integer NOT NULL
);

COMMENT ON TABLE public.recipe_ingredients IS
'One row per ingredient line. The ingredient is a SHARED Atlas row; there '
'is deliberately no per-recipe ingredients table (ADR-007).';

-- The recipe's own sentences. LANGUAGE-FIRST (ADR-007-A1 §4.3), which
-- is the MIRROR IMAGE of `description_sentences`, whose CHECK makes
-- English the source language.
--
-- Here the ORIGINAL-language sentence is the one with
-- `source_sentence_id IS NULL`, and every other locale points at it.
--
-- THE SELF-REFERENCE IS `ON DELETE RESTRICT`, not `ON DELETE SET NULL`.
-- A translation's source must not be deleted out from under it: SET
-- NULL would leave the translation with no source, which violates
-- the language-first CHECK below -- so the delete would fail with a
-- confusing constraint error instead of a clear foreign-key one.
CREATE TABLE IF NOT EXISTS public.recipe_sentences (
  id                 uuid PRIMARY KEY DEFAULT uuid_generate_v4(),
  recipe_id          uuid NOT NULL REFERENCES public.recipes(id) ON DELETE CASCADE,
  field              text NOT NULL DEFAULT 'step'
                        CHECK (field IN ('step','note','intro')),
  locale             text NOT NULL DEFAULT 'en',
  position           integer NOT NULL,
  text               text NOT NULL,
  source_sentence_id uuid REFERENCES public.recipe_sentences(id) ON DELETE RESTRICT,
  anchor_status      text NOT NULL DEFAULT 'none'
                        CHECK (anchor_status IN ('full','partial','none')),
  -- ADR-007-A1 §4.3: exactly ONE row per recipe is the original.
  --
  -- It is NOT NULL DEFAULT false, so a row that does not declare
  -- itself a translation is refused by the CHECK below rather than
  -- silently becoming an orphan.
  is_original        boolean NOT NULL DEFAULT false,
  created_at         timestamptz NOT NULL DEFAULT now(),
  updated_at         timestamptz NOT NULL DEFAULT now()
);

COMMENT ON TABLE public.recipe_sentences IS
'The recipe''s sentences, LANGUAGE-FIRST (ADR-007-A1 §4.3): the original '
'locale''s sentence has source_sentence_id IS NULL and is_original=true, '
'and every other locale points at it. This is the mirror image of '
'description_sentences, which stays untouched -- the Atlas dish pages '
'are not part of this task.';

-- The link from a recipe sentence to the statement that backs it.
--
-- A SEPARATE table, not a widened `sentence_claims` (ADR-007, Option A):
-- `sentence_claims.sentence_id` carries a FOREIGN KEY to
-- `description_sentences(id)`, and a recipe sentence is not a
-- description sentence.
CREATE TABLE IF NOT EXISTS public.recipe_claims (
  recipe_sentence_id uuid NOT NULL REFERENCES public.recipe_sentences(id) ON DELETE CASCADE,
  statement_id       uuid NOT NULL REFERENCES public.statements(id) ON DELETE CASCADE,
  is_primary         boolean NOT NULL DEFAULT true,
  created_at         timestamptz NOT NULL DEFAULT now(),
  PRIMARY KEY (recipe_sentence_id, statement_id)
);

COMMENT ON TABLE public.recipe_claims IS
'The recipe-scoped claim link. A SEPARATE table from sentence_claims on '
'purpose (ADR-007 Option A): sentence_claims.sentence_id is FK-bound to '
'description_sentences(id) and cannot carry a recipe sentence. The '
'`statements` table -- where the provenance lives -- is SHARED.';

-- Translations, scoped to the recipe, plus the `is_original` marker that
-- gives the "primary title" question one answer (ADR-007-A1 §4.3).
CREATE TABLE IF NOT EXISTS public.recipe_translations (
  recipe_id    uuid NOT NULL REFERENCES public.recipes(id) ON DELETE CASCADE,
  locale       text NOT NULL,
  title        text NOT NULL,
  description  text,
  is_original  boolean NOT NULL DEFAULT false,
  PRIMARY KEY (recipe_id, locale)
);

COMMENT ON TABLE public.recipe_translations IS
'The recipe''s title and description per locale, plus the is_original '
'marker on the recipe''s own language (ADR-007-A1 §4.3).';

-- The LANGUAGE-FIRST check, as a constraint.
--
-- Two rules, in one constraint:
--   1. a sentence marked `is_original` must have NO source (it IS the
--      original), and a sentence that is not original MUST have one;
--   2. a translation's source must point at an original row of the SAME
--      recipe.
--
-- Rule 2 cannot be a CHECK constraint: a CHECK cannot see other rows.
-- It is a trigger, below.
ALTER TABLE public.recipe_sentences
  DROP CONSTRAINT IF EXISTS recipe_sentences_original_source_check;
ALTER TABLE public.recipe_sentences
  ADD CONSTRAINT recipe_sentences_original_source_check
  CHECK (
    (is_original AND source_sentence_id IS NULL)
    OR (NOT is_original AND source_sentence_id IS NOT NULL)
  );

COMMENT ON CONSTRAINT recipe_sentences_original_source_check ON public.recipe_sentences IS
'LANGUAGE-FIRST (ADR-007-A1 §4.3): the original-language sentence is the '
'one with source_sentence_id IS NULL. The mirror image of the '
'description_sentences CHECK, which is unchanged.';

-- Rule 2, as a trigger: a translation must point at an original row of
-- the SAME recipe, and there must be exactly one original per recipe.
CREATE OR REPLACE FUNCTION public.recipe_sentences_language_first_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $guard$
DECLARE
  v_source_recipe uuid;
  v_source_is_original boolean;
  v_original_count integer;
  v_recipe uuid;
BEGIN
  -- The recipe this row belongs to. On DELETE, NEW is NULL, so it must
  -- come from OLD.
  IF TG_OP = 'DELETE' THEN
    v_recipe := OLD.recipe_id;
  ELSE
    v_recipe := NEW.recipe_id;
  END IF;

  -- (1) THE SOURCE MUST BE AN ORIGINAL ROW OF THE SAME RECIPE.
  IF TG_OP <> 'DELETE' AND NEW.source_sentence_id IS NOT NULL THEN
    SELECT recipe_id, is_original
      INTO v_source_recipe, v_source_is_original
      FROM public.recipe_sentences
     WHERE id = NEW.source_sentence_id;

    IF v_source_recipe IS NULL THEN
      RAISE EXCEPTION
        'the recipe sentence % points at a source sentence that does not exist',
        NEW.id;
    END IF;

    IF v_source_recipe <> NEW.recipe_id THEN
      RAISE EXCEPTION
        'the recipe sentence % points at a source sentence belonging to a different recipe',
        NEW.id;
    END IF;

    IF NOT v_source_is_original THEN
      RAISE EXCEPTION
        'the recipe sentence % points at a source sentence that is not an original',
        NEW.id;
    END IF;
  END IF;

  -- (2) EXACTLY ONE ORIGINAL PER RECIPE.
  --
  -- The count is taken over the rows of THIS recipe, excluding the row
  -- being written -- so the rule is enforced on the row's own value,
  -- not on the count after the write.
  IF TG_OP <> 'DELETE' AND NEW.is_original THEN
    SELECT count(*) INTO v_original_count
      FROM public.recipe_sentences
     WHERE recipe_id = NEW.recipe_id
       AND is_original
       AND id IS DISTINCT FROM NEW.id;

    IF v_original_count >= 1 THEN
      RAISE EXCEPTION
        'the recipe % already has an original sentence -- there must be exactly one',
        NEW.recipe_id;
    END IF;
  END IF;

  RETURN NEW;
END;
$guard$;

COMMENT ON FUNCTION public.recipe_sentences_language_first_guard() IS
'LANGUAGE-FIRST (ADR-007-A1 §4.3), as a trigger, because a CHECK cannot '
'see other rows. A translation must point at an ORIGINAL sentence of the '
'SAME recipe, and a recipe must have exactly ONE original. The original '
'is the one whose source_sentence_id IS NULL.';

DROP TRIGGER IF EXISTS recipe_sentences_language_first_trg ON public.recipe_sentences;
CREATE TRIGGER recipe_sentences_language_first_trg
  BEFORE INSERT OR UPDATE OF recipe_id, source_sentence_id, is_original
    ON public.recipe_sentences
  FOR EACH ROW EXECUTE FUNCTION public.recipe_sentences_language_first_guard();

-- ═══════════════════════════════════════════════════════════════════════
-- PART 2 -- THE INGREDIENT SLUG GUARD (§3.4)
-- ═══════════════════════════════════════════════════════════════════════

-- A published ingredient's slug is part of a published URL, so it must
-- not change under a reader's feet. The guard refuses the change and
-- says why.
CREATE OR REPLACE FUNCTION public.ingredients_published_slug_guard()
RETURNS trigger
LANGUAGE plpgsql
AS $guard$
BEGIN
  IF NEW.slug IS DISTINCT FROM OLD.slug
     AND OLD.status = 'published' THEN
    RAISE EXCEPTION
      'the slug of the published ingredient % may not change from % to % -- '
      'it is part of a published URL. Publish a new ingredient instead.',
      OLD.id, OLD.slug, NEW.slug;
  END IF;
  RETURN NEW;
END;
$guard$;

COMMENT ON FUNCTION public.ingredients_published_slug_guard() IS
'Refuses a slug change on a PUBLISHED ingredient (ADR-007-A1 §3.4). The '
'slug is part of a published URL, so changing it breaks the link a '
'reader has. An unpublished ingredient may be renamed freely.';

DROP TRIGGER IF EXISTS ingredients_published_slug_guard_trg ON public.ingredients;
CREATE TRIGGER ingredients_published_slug_guard_trg
  BEFORE UPDATE OF slug ON public.ingredients
  FOR EACH ROW EXECUTE FUNCTION public.ingredients_published_slug_guard();

