-- ═══════════════════════════════════════════════════════════════════════
-- PART 7 -- THE CONFIDENCE COMPUTATION
-- ═══════════════════════════════════════════════════════════════════════

-- The level ordering, so "the first failure decides" can be applied
-- mechanically.
CREATE OR REPLACE FUNCTION public.recipe_level_least(a text, b text)
RETURNS text
LANGUAGE sql
IMMUTABLE
AS $$
  SELECT CASE
    WHEN a = 'low' OR b = 'low' THEN 'low'
    WHEN a = 'medium' OR b = 'medium' THEN 'medium'
    ELSE 'high'
  END;
$$;

COMMENT ON FUNCTION public.recipe_level_least(text,text) IS
'The severity ordering of the confidence levels: low < medium < high. '
'Used by recipe_compute_confidence() so that "the first failure decides '
'the level" is applied mechanically rather than by hand at each step.';

-- The confidence of a recipe, COMPUTED FROM THE ROWS.
--
-- 'high' requires EVERY condition; there is no scoring. The conditions
-- are evaluated in order and the FIRST failure decides the level, with
-- the reason recorded (ADR-007-A1 §8.3).
--
-- The function returns a JSON object:
--   { level, conditions_met, independent_sources, sources,
--     source_count, ingredient_count, sentence_count }
--
-- `conditions_met` is an object keyed by condition id, each value
-- { met: boolean, detail: text }.
--
-- THE CONDITIONS (ADR-007-A1 §8.3)
--   1  the dish is published                        -> medium (low if missing)
--   2  every ingredient is a PUBLISHED ingredient    -> medium
--   3  the recipe has at least one sentence          -> low
--   4  every sentence has a claim whose statement is
--      EVIDENCED -- see the note below                -> medium
--   5  every claim's statement has a `supports`
--      citation from an S1-S5 source                 -> medium
--   5a NO contributing source is S6/S7               -> medium
--   6  >=2 INDEPENDENT sources on the core claims    -> medium
--   7' every core claim has a citation with an exact
--      LOCATOR, and the sources satisfy 1.2 and 1.3  -> medium
--   8  the recipe is not a draft-only stub           -> low
--
-- CONDITIONS 5a AND 7' ARE THE OWNER'S 2026-11-08 ADDITIONS and are
-- NOT restatements of 5 and 6:
--   * 5 asks "is there at least one S1-S5 source?"; 5a asks "are ALL
--     of the contributing sources S1-S5?". A recipe with one cookbook
--     source and three Wikipedia citations satisfies 5 and fails 5a.
--   * 7' asks about the POINTER to the evidence, not the sources: a
--     reader must be able to be sent to the exact place that supports
--     the claim.
--
-- CONDITION 4 -- THE CIRCULARITY, AND HOW IT IS READ HERE.
--
-- The ADR's condition 4 is "every sentence has a claim with a
-- statement at status IN ('verified','published')". Taken literally
-- against the CURRENT status, the recipe can only be HIGH once it is
-- already published -- and §8.4's function, whose job is to make it
-- published, could never succeed. That is not a reading anybody
-- intends, and it would make the auto-publish function dead code.
--
-- So condition 4 is read here as the PRE-TRANSITION question: every
-- sentence must have a claim whose statement is EVIDENCED -- that is,
-- it carries the supporting S1-S5 citations, a locator, and the
-- independence the other conditions require -- and the function is
-- what LIFTS those statements from their evidence to
-- verified/published. The confidence asks "is this sentence backed by
-- evidence?"; the transition is the consequence of that answer.
--
-- The PUBLISH VIEW still keys on the POST-transition status, so a
-- recipe is only publishable once its statements really are verified.
-- The two questions are asked at different moments, and neither
-- contradicts the other. This is recorded as a deviation for the owner
-- to confirm: docs/MIGRATION-RECEIPT-0052.md §3.
CREATE OR REPLACE FUNCTION public.recipe_compute_confidence(p_recipe_id uuid)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
AS $fn$
DECLARE
  v_recipe         public.recipes%ROWTYPE;
  v_dish_ok        boolean := false;
  v_dish_missing   boolean := false;
  v_c_5a           jsonb;
  v_c_6            jsonb;
  v_c_7            jsonb;
  v_conds          jsonb := '{}'::jsonb;
  v_sources        jsonb := '[]'::jsonb;
  v_independent    jsonb := '[]'::jsonb;
  v_source_count   integer := 0;
  v_ingredient_count integer := 0;
  v_sentence_count integer := 0;
  v_level          text := 'high';
  v_core_statements uuid[];
  v_support_sources uuid[];
  v_indep_count    integer := 0;
BEGIN
  SELECT * INTO v_recipe FROM public.recipes WHERE id = p_recipe_id;
  IF NOT FOUND THEN
    RETURN jsonb_build_object(
      'level', 'low',
      'conditions_met', jsonb_build_object('1', jsonb_build_object('met', false, 'detail', 'the recipe does not exist')),
      'independent_sources', '[]'::jsonb,
      'sources', '[]'::jsonb,
      'source_count', 0, 'ingredient_count', 0, 'sentence_count', 0);
  END IF;

  -- (1) THE DISH IS PUBLISHED.
  IF NOT EXISTS (SELECT 1 FROM public.dishes d WHERE d.id = v_recipe.dish_id) THEN
    v_dish_missing := true;
  ELSE
    SELECT (status = 'published') INTO v_dish_ok FROM public.dishes d WHERE d.id = v_recipe.dish_id;
  END IF;

  -- (2) EVERY INGREDIENT IS A PUBLISHED INGREDIENT.
  SELECT count(*) INTO v_ingredient_count
    FROM public.recipe_ingredients ri WHERE ri.recipe_id = p_recipe_id;

  -- (3) THE RECIPE HAS AT LEAST ONE SENTENCE.
  SELECT count(*) INTO v_sentence_count
    FROM public.recipe_sentences rs WHERE rs.recipe_id = p_recipe_id;

  -- THE CORE CLAIMS: the statements behind the recipe's sentences.
  SELECT coalesce(array_agg(DISTINCT rc.statement_id), '{}'::uuid[])
    INTO v_core_statements
    FROM public.recipe_sentences rs
    JOIN public.recipe_claims rc ON rc.recipe_sentence_id = rs.id
   WHERE rs.recipe_id = p_recipe_id;

  -- (5) THE S1-S5 SOURCES THAT SUPPORT A CORE CLAIM.
  IF array_length(v_core_statements, 1) IS NULL THEN
    v_support_sources := '{}'::uuid[];
  ELSE
    SELECT coalesce(array_agg(DISTINCT c.source_id), '{}'::uuid[])
      INTO v_support_sources
      FROM public.claim_citations c
      JOIN public.sources src ON src.id = c.source_id
     WHERE c.statement_id = ANY(v_core_statements)
       AND c.stance = 'supports'
       AND src.source_class IN ('S1','S2','S3','S4','S5');
  END IF;

  v_source_count := coalesce(array_length(v_support_sources, 1), 0);

  -- (5a) NO CONTRIBUTING SOURCE IS S6/S7.
  --
  -- This asks about ALL the sources that contribute a `supports`
  -- citation -- not just the S1-S5 ones. A recipe with one cookbook
  -- source and three Wikipedia citations satisfies 5 and FAILS 5a.
  IF EXISTS (
    SELECT 1
      FROM public.claim_citations c
      JOIN public.sources src ON src.id = c.source_id
     WHERE c.statement_id = ANY(v_core_statements)
       AND c.stance = 'supports'
       AND (src.source_class IS NULL OR src.source_class IN ('S6','S7'))
  ) THEN
    v_c_5a := jsonb_build_object('met', false,
      'detail', 'a contributing source is S6/S7 -- a Wikipedia-only recipe is never HIGH');
  ELSE
    v_c_5a := jsonb_build_object('met', true, 'detail', 'every contributing source is S1-S5');
  END IF;

  -- (6) >=2 INDEPENDENT SOURCES ON THE CORE CLAIMS.
  --
  -- Independence is a property of the SOURCES, not of the count of
  -- citations: two citations from one source are one source. The
  -- `statements.independence` column records a per-statement finding;
  -- where it says `dependent`, that source does not count toward the
  -- two.
  SELECT count(DISTINCT src.id) INTO v_indep_count
    FROM public.claim_citations c
    JOIN public.sources src ON src.id = c.source_id
    JOIN public.statements st ON st.id = c.statement_id
   WHERE c.statement_id = ANY(v_core_statements)
     AND c.stance = 'supports'
     AND src.source_class IN ('S1','S2','S3','S4','S5')
     AND coalesce(st.independence, 'single') <> 'dependent';

  IF v_indep_count >= 2 THEN
    v_c_6 := jsonb_build_object('met', true,
      'detail', format('%s independent sources', v_indep_count));
  ELSE
    v_c_6 := jsonb_build_object('met', false,
      'detail', format('only %s independent source(s) -- 2 are required', v_indep_count));
  END IF;

  -- (7') EVERY CORE CLAIM HAS A CITATION WITH AN EXACT LOCATOR.
  --
  -- Every CORE CLAIM must have one -- not merely some of them. The
  -- count of claims without a located citation must be zero.
  IF EXISTS (
    SELECT 1
      FROM unnest(v_core_statements) AS s(statement_id)
     WHERE NOT EXISTS (
       SELECT 1 FROM public.claim_citations c
        WHERE c.statement_id = s.statement_id
          AND c.stance = 'supports'
          AND c.locator IS NOT NULL
          AND btrim(c.locator) <> '')
  ) THEN
    v_c_7 := jsonb_build_object('met', false,
      'detail', 'a core claim has no citation carrying an exact locator');
  ELSE
    v_c_7 := jsonb_build_object('met', true,
      'detail', 'every core claim has a citation carrying an exact locator');
  END IF;

  -- THE SOURCES THAT SATISFIED THE INDEPENDENCE CONDITION, for the log
  -- and the digest (§7.3).
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'source_id', src.id,
           'title', src.title,
           'source_class', src.source_class
         ) ORDER BY src.title), '[]'::jsonb)
    INTO v_independent
    FROM public.claim_citations c
    JOIN public.sources src ON src.id = c.source_id
    JOIN public.statements st ON st.id = c.statement_id
   WHERE c.statement_id = ANY(v_core_statements)
     AND c.stance = 'supports'
     AND src.source_class IN ('S1','S2','S3','S4','S5')
     AND coalesce(st.independence, 'single') <> 'dependent';

  -- EVERY CONTRIBUTING SOURCE, with a locator when it has one. The
  -- LOCATOR is the rendered part of the provenance; the excerpt is
  -- internal-only and is never included here (§1.4).
  --
  -- THE LOCATOR IS AGGREGATED IN A SUBQUERY, NOT IN THE AGGREGATE.
  -- `min(c.locator)` cannot be written inside `jsonb_agg(...)` --
  -- PostgreSQL refuses an aggregate nested inside an aggregate with
  -- "aggregate function calls cannot be nested". So the locators are
  -- collapsed per source FIRST, and the outer aggregate builds the
  -- JSON from the result.
  SELECT coalesce(jsonb_agg(jsonb_build_object(
           'source_id', src.id,
           'title', src.title,
           'source_class', src.source_class,
           'locator', agg.locator
         ) ORDER BY src.title), '[]'::jsonb)
    INTO v_sources
    FROM (
      SELECT c.source_id, min(c.locator) AS locator
        FROM public.claim_citations c
       WHERE c.statement_id = ANY(v_core_statements)
         AND c.stance = 'supports'
       GROUP BY c.source_id
    ) agg
    JOIN public.sources src ON src.id = agg.source_id;

  -- ── THE CONDITIONS, IN ORDER. The FIRST failure decides the level. ──
  -- 1 -- the dish is published.
  IF v_dish_missing THEN
    v_conds := v_conds || jsonb_build_object('1',
      jsonb_build_object('met', false, 'detail', 'the dish does not exist'));
    v_level := 'low';
  ELSIF NOT v_dish_ok THEN
    v_conds := v_conds || jsonb_build_object('1',
      jsonb_build_object('met', false, 'detail', 'the dish is not published'));
    v_level := 'medium';
  ELSE
    v_conds := v_conds || jsonb_build_object('1',
      jsonb_build_object('met', true, 'detail', 'the dish is published'));
  END IF;

  -- 2 -- every ingredient is a published ingredient.
  IF v_ingredient_count = 0 THEN
    v_conds := v_conds || jsonb_build_object('2',
      jsonb_build_object('met', false, 'detail', 'the recipe has no ingredients'));
    v_level := public.recipe_level_least(v_level, 'medium');
  ELSIF EXISTS (
    SELECT 1 FROM public.recipe_ingredients ri
      JOIN public.ingredients i ON i.id = ri.ingredient_id
     WHERE ri.recipe_id = p_recipe_id AND i.status <> 'published'
  ) THEN
    v_conds := v_conds || jsonb_build_object('2',
      jsonb_build_object('met', false, 'detail', 'an ingredient is not published'));
    v_level := public.recipe_level_least(v_level, 'medium');
  ELSE
    v_conds := v_conds || jsonb_build_object('2',
      jsonb_build_object('met', true, 'detail', 'every ingredient is published'));
  END IF;

  -- 3 -- at least one sentence.
  IF v_sentence_count = 0 THEN
    v_conds := v_conds || jsonb_build_object('3',
      jsonb_build_object('met', false, 'detail', 'the recipe has no sentences'));
    v_level := public.recipe_level_least(v_level, 'low');
  ELSE
    v_conds := v_conds || jsonb_build_object('3',
      jsonb_build_object('met', true, 'detail', format('%s sentences', v_sentence_count)));
  END IF;

  -- 4 -- every sentence has a claim whose statement is EVIDENCED.
  --
  -- THE PRE-TRANSITION READING -- see the note at the top of this
  -- function. The statement must exist, and it must carry the
  -- supporting evidence: at least one `supports` citation from an
  -- S1-S5 source, and it must not be `unsupported` or a `disputed`
  -- class. A statement already at verified/published also passes --
  -- so the condition is true both BEFORE and AFTER the transition,
  -- which is what makes it usable by both the confidence computation
  -- and the publish view.
  IF EXISTS (
    SELECT 1
      FROM public.recipe_sentences rs
      LEFT JOIN public.recipe_claims rc ON rc.recipe_sentence_id = rs.id
      LEFT JOIN public.statements st ON st.id = rc.statement_id
     WHERE rs.recipe_id = p_recipe_id
       AND (st.id IS NULL
            OR st.claim_class IN ('unsupported','disputed')
            OR NOT EXISTS (
                 SELECT 1 FROM public.claim_citations c
                   JOIN public.sources src ON src.id = c.source_id
                  WHERE c.statement_id = st.id
                    AND c.stance = 'supports'
                    AND src.source_class IN ('S1','S2','S3','S4','S5')))
  ) THEN
    v_conds := v_conds || jsonb_build_object('4',
      jsonb_build_object('met', false,
        'detail', 'a sentence has no claim, or its statement is not evidenced'));
    v_level := public.recipe_level_least(v_level, 'medium');
  ELSE
    v_conds := v_conds || jsonb_build_object('4',
      jsonb_build_object('met', true, 'detail', 'every sentence has an evidenced statement'));
  END IF;

  -- 5 -- every claim's statement has a supports citation from S1-S5.
  IF v_source_count = 0 THEN
    v_conds := v_conds || jsonb_build_object('5',
      jsonb_build_object('met', false, 'detail', 'no S1-S5 source supports the claims'));
    v_level := public.recipe_level_least(v_level, 'medium');
  -- NB: the literal text after the placeholder is written as "S1-S5
  -- sources" and not "source(s)": in `format()`, a parenthesised
  -- group directly after a placeholder is parsed as a TYPE SPECIFIER
  -- (`%s(...)` is a width/precision spec), so "source(s)" raises
  -- "unrecognized format() type specifier".
  ELSE
    v_conds := v_conds || jsonb_build_object('5',
      jsonb_build_object('met', true, 'detail', format('%s S1-S5 sources', v_source_count)));
  END IF;

  -- 5a, 6 and 7' -- the conditions computed above, each kept separate.
  v_conds := v_conds || jsonb_build_object('5a', v_c_5a);
  v_conds := v_conds || jsonb_build_object('6', v_c_6);
  v_conds := v_conds || jsonb_build_object('7', v_c_7);

  -- 8 -- not a draft-only stub.
  IF v_recipe.servings IS NULL
     AND v_recipe.prep_minutes IS NULL
     AND v_recipe.cook_minutes IS NULL THEN
    v_conds := v_conds || jsonb_build_object('8',
      jsonb_build_object('met', false, 'detail', 'the recipe is a stub: no servings and no times'));
    v_level := public.recipe_level_least(v_level, 'low');
  ELSE
    v_conds := v_conds || jsonb_build_object('8',
      jsonb_build_object('met', true, 'detail', 'the recipe carries servings or times'));
  END IF;

  RETURN jsonb_build_object(
    'level', v_level,
    'conditions_met', v_conds,
    'independent_sources', v_independent,
    'sources', v_sources,
    'source_count', v_source_count,
    'ingredient_count', v_ingredient_count,
    'sentence_count', v_sentence_count);
END;
$fn$;

COMMENT ON FUNCTION public.recipe_compute_confidence(uuid) IS
'Computes a recipe''s confidence FROM THE ROWS (ADR-007-A1 §8.3). '
'''high'' requires EVERY condition; there is no scoring. The conditions are '
'evaluated in order and the first failure decides the level. conditions_met '
'holds every condition result, so a MEDIUM recipe says WHICH condition '
'failed -- which is what the owner reviews. Condition 4 is read as the '
'PRE-TRANSITION question ("is the sentence evidenced?"), because the '
