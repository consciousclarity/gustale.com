#!/usr/bin/env node
/**
 * THE REDIRECT RULES — generated from one map.
 *
 * WHY THIS IS A SCRIPT AND NOT A HAND-WRITTEN BLOCK
 * -------------------------------------------------
 * The blueprint asks for old-to-new redirects for `/map`, `/regions`,
 * `/lineages` and `/family/*`, and the map that says where each one
 * goes lives in `apps/web/src/lib/redirects.ts` — because the site
 * needs to know it too, not just nginx.
 *
 * A hand-written nginx block would be a SECOND copy of that map, and
 * the two would drift. This script reads the map and writes the
 * nginx block, so there is one answer.
 *
 * THE 404 RULE
 * -------------
 * A 301 to a 404 is worse than no redirect: it tells a search engine
 * the page is gone and gives the reader a dead end. So only the rules
 * whose TARGET exists are emitted, and the script says which ones it
 * held back and why.
 *
 * Usage:
 *   node apps/web/scripts/generate-redirect-rules.mjs          # print the block
 *   node apps/web/scripts/generate-redirect-rules.mjs --write   # write it into nginx.conf
 *   node apps/web/scripts/generate-redirect-rules.mjs --check   # verify nginx.conf
 */

import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const REPO = join(HERE, "..", "..", "..");
const MAP_PATH = join(REPO, "apps", "web", "src", "lib", "redirects.ts");

/**
 * The redirect map, read from the TypeScript source.
 *
 * The source is parsed rather than imported, because it is TypeScript
 * and this script runs under plain node. The parse looks for the
 * `from:`/`to:`/`targetExists:` fields of each rule object, which is
 * the only structured data in the file.
 */
function readRedirectRules() {
  const src = readFileSync(MAP_PATH, "utf8");

  const rules = [];
  const re =
    /from:\s*"([^"]+)",\s*\n\s*to:\s*"([^"]+)",[\s\S]*?targetBuiltBy:\s*"([^"]+)",[\s\S]*?targetExists:\s*(true|false),/g;
  let m;
  while ((m = re.exec(src)) !== null) {
    rules.push({
      from: m[1],
      to: m[2],
      builtBy: m[3],
      targetExists: m[4] === "true",
    });
  }
  if (rules.length === 0) {
    throw new Error(
      "no redirect rules found in apps/web/src/lib/redirects.ts -- the parser needs updating",
    );
  }
  return rules;
}

/**
 * The nginx block.
 *
 * `permanent` is nginx's 301. The rules are emitted in the map's
 * order, and the map puts the more specific prefixes first.
 */
export function nginxRedirectBlock(rules) {
  const active = rules.filter((r) => r.targetExists);
  const held = rules.filter((r) => !r.targetExists);

  const lines = [
    "    # ─── THE OLD-TO-NEW PATHS ──────────────────────────────────────",
    "    # Generated by apps/web/scripts/generate-redirect-rules.mjs from",
    "    # apps/web/src/lib/redirects.ts. Do not hand-edit: the map is the",
    "    # source of truth, and this script is what writes it out.",
    "    #",
  ];

  if (held.length > 0) {
    lines.push(
      "    # HELD: the target does not exist yet, and a 301 to a 404 is",
      "    # worse than no redirect at all.",
    );
    for (const r of held) {
      lines.push(`    #   ${r.from} -> ${r.to}   (${r.builtBy})`);
    }
    lines.push("");
  }

  if (active.length === 0) {
    lines.push("    # (no redirect is active on this build yet)", "");
    return lines.join("\n");
  }

  for (const r of active) {
    lines.push(`    # ${r.from} -> ${r.to}`);
    lines.push(`    location ^~ ${r.from} {`);
    lines.push(`        return 301 ${r.to}$is_args$args;`);
    lines.push("    }");
    lines.push("");
  }

  return lines.join("\n");
}

// ─── the CLI ────────────────────────────────────────────────────────────
const isMain =
  process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1];
if (isMain) {
  const rules = readRedirectRules();
  const block = nginxRedirectBlock(rules);

  if (process.argv.includes("--write")) {
    // WRITE THE BLOCK INTO nginx.conf.
    //
    // The block is bounded by two stable markers: the header comment
    // that says the map generated it, and the first thing after it that
    // is not part of it. Replacing exactly that region -- and nothing
    // else -- is what keeps the rest of the file (the cache headers,
    // the try_files, the rewrites) untouched.
    const NGINX_PATH = join(REPO, "apps", "web", "nginx.conf");
    const nginx = readFileSync(NGINX_PATH, "utf8");

    const START = "    # ─── THE OLD-TO-NEW PATHS";
    const END = "    # HTML pages — never cache";

    const startAt = nginx.indexOf(START);
    const endAt = nginx.indexOf(END);
    if (startAt === -1 || endAt === -1 || endAt < startAt) {
      console.error(
        "nginx.conf does not carry the redirect block's markers; refusing to guess where it ends.",
      );
      process.exit(1);
    }

    const next = nginx.slice(0, startAt) + block + "\n" + nginx.slice(endAt);
    if (next === nginx) {
      console.log("nginx.conf already carries this block. Nothing to do.");
    } else {
      writeFileSync(NGINX_PATH, next);
      console.log(
        `nginx.conf updated: ${rules.filter((r) => r.targetExists).length} active redirect(s), ${rules.filter((r) => !r.targetExists).length} held back.`,
      );
    }
  } else if (process.argv.includes("--check")) {
    const nginx = readFileSync(join(REPO, "apps", "web", "nginx.conf"), "utf8");
    const missing = rules
      .filter((r) => r.targetExists)
      .filter((r) => !nginx.includes(`location ^~ ${r.from} {`));
    if (missing.length > 0) {
      console.error(
        `nginx.conf is missing ${missing.length} redirect(s): ${missing
          .map((r) => r.from)
          .join(", ")}`,
      );
      process.exit(1);
    }
    console.log("nginx.conf carries every active redirect.");
    const held = rules.filter((r) => !r.targetExists);
    if (held.length > 0) {
      console.log("Held back until their target exists:");
      for (const h of held) {
        console.log(`  ${h.from} -> ${h.to}   (${h.builtBy})`);
      }
    }
  } else {
    process.stdout.write(block);
  }
}
