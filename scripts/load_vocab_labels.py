#!/usr/bin/env python3
"""Load the fetched Wikidata labels into vocabulary_labels.

The input is /tmp/vocab_labels.json, produced by
scripts/fetch_vocab_labels.py:

    { vocabulary: { key: { locale: {"name": ..., "tag": ...,
                                    "source": "wikidata"} } } }

and /tmp/vocab_qids.json, which maps the same keys to Wikidata QIDs.

Each vocabulary's rows are looked up by their own key (a slug, or an
iso_code for places), and one row per (value, locale) is inserted.

TWO THINGS THIS SCRIPT IS CAREFUL ABOUT:

1. THE QID IS STORED ON THE VALUE, not only in the label row. The
   vocabulary_labels.source_ref column records where a label came
   from, but the value's own wikidata_id column is what lets the
   label job re-check or re-fetch it. So both are written: the QID
   onto the value, and the label into vocabulary_labels.

2. ENGLISH IS NEVER WRITTEN. It stays in the base table's own `name`
   column, and the migration's post-assertion enforces that. The
   fetcher already excludes it, and this script filters again so a
   bug upstream cannot duplicate it.

Output: the SQL for the data migration, plus the QID updates.
"""

import json
import pathlib
import subprocess
import sys

LABELS_PATH = pathlib.Path("/tmp/vocab_labels.json")
QIDS_PATH = pathlib.Path("/tmp/vocab_qids.json")
OUT_PATH = pathlib.Path("/tmp/vocab_labels.sql")
MIGRATION_PATH = pathlib.Path("db/migrations/0022_adr003_vocabulary_labels.sql")

# vocabulary -> (table, key column, key expression)
# For places the key is the iso_code, which is what the QID map uses.
TARGETS = {
    "country": ("geo_entities", "iso_code", "entity_type = 'country'"),
    "region": ("geo_entities", "iso_code", "entity_type = 'region'"),
    "cuisine": ("dish_cuisines", "slug", None),
    "family": ("dish_families", "slug", None),
    "technique": ("dish_techniques", "slug", None),
    "tradition": ("dish_traditions", "slug", None),
    "context": ("dish_contexts", "slug", None),
    "ingredient_category": ("ingredient_categories", "slug", None),
    "predicate": ("relation_types", "slug", None),
}

CORE_LOCALES = ["es", "de", "fr", "pt", "id", "zh", "ja", "ar", "hi"]


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    if not LABELS_PATH.exists():
        print(f"ERROR: {LABELS_PATH} does not exist - run fetch_vocab_labels.py first")
        return 1

    labels = json.loads(LABELS_PATH.read_text())
    qids = json.loads(QIDS_PATH.read_text()) if QIDS_PATH.exists() else {}

    # --- 1. the QID updates ---------------------------------------------
    # The value's own wikidata_id column. For places the QID is already
    # there; for the others this is the first time it is set.
    qid_sql = []
    for vocab, (table, keycol, extra) in TARGETS.items():
        mapping = qids.get(vocab) or {}
        if not mapping:
            continue
        for key, qid in mapping.items():
            if not qid:
                continue
            where = f"{keycol} = {q(key)}"
            if extra:
                where += f" AND {extra}"
            qid_sql.append(
                f"UPDATE {table} SET wikidata_id = {q(qid)} "
                f" WHERE {where} AND wikidata_id IS NULL;"
            )

    # --- 2. the label rows ----------------------------------------------
    # The value_id is resolved by a subquery on the value's own key,
    # so the SQL is self-contained and does not depend on the UUIDs
    # being stable between the export and the apply.
    label_sql = []
    total_rows = 0
    for vocab, (table, keycol, extra) in TARGETS.items():
        mapping = labels.get(vocab) or {}
        if not mapping:
            continue
        rows = []
        for key, per_locale in mapping.items():
            for locale, entry in per_locale.items():
                if locale not in CORE_LOCALES:
                    continue
                name = (entry.get("name") or "").strip()
                if not name:
                    continue
                rows.append(
                    f"  ({q(vocab)}, {q(key)}, {q(locale)}, {q(name)}, "
                    f"{q(entry.get('source') or 'wikidata')}, "
                    f"{q(qids.get(vocab, {}).get(key) or entry.get('source_ref'))})"
                )
        if not rows:
            continue
        label_sql.append(f"-- {vocab} ({len(rows)} label rows)")
        label_sql.append("INSERT INTO _vocab_label_stage "
                         "(vocabulary, value_key, language, name, source, source_ref)")
        label_sql.append("VALUES")
        label_sql.append(",\n".join(rows))
        label_sql.append(";")
        label_sql.append("")
        total_rows += len(rows)

    L = []
    A = L.append
    A("-- GUS-242 / ADR-003 layer 1 — the vocabulary labels.")
    A("--")
    A("-- Generated by scripts/load_vocab_labels.py from")
    A("-- /tmp/vocab_labels.json and /tmp/vocab_qids.json. Do not hand-edit:")
    A("-- regenerate.")
    A("--")
    A(f"-- {len(qid_sql)} values gain a Wikidata QID; {total_rows} labels are")
    A("-- written for the nine non-English core locales.")
    A("--")
    A("-- English is NOT here: it stays in each base table's own `name` column,")
    A("-- and the migration's post-assertion enforces that.")
    A("")
    A("\\set ON_ERROR_STOP on")
    A("")
    A("-- IDEMPOTENT")
    A("--")
    A("-- Safe to re-apply: the guard is TRUE when the migration still")
    A("-- needs to run - that is, when the labels are not yet there. It")
    A("-- was written the other way round on the first attempt, and the")
    A("-- dry-run showed it: the migration skipped on a fresh database")
    A("-- and the 'already applied' message appeared on the very first")
    A("-- apply.")
    A("SELECT")
    A("  NOT (")
    A("    (SELECT count(*) FROM vocabulary_labels) >= 35000")
    A("    AND")
    A("    (SELECT count(DISTINCT language) FROM vocabulary_labels) >= 9")
    A("  ) AS need_to_run \\gset")
    A("\\if :need_to_run")
    A("\\echo 'GUS-242: the vocabulary labels are not yet applied - applying them'")
    A("")
    A("BEGIN;")
    A("")
    A("-- =====================================================================")
    A("-- THE WIKIDATA QIDs")
    A("--")
    A("-- Stored on the VALUE, so the label job can re-check or re-fetch")
    A("-- them. The vocabulary_labels.source_ref column records the same QID")
    A("-- against the label.")
    A("-- =====================================================================")
    A("")
    if qid_sql:
        A("\n".join(qid_sql))
    A("")
    A("-- =====================================================================")
    A("-- THE LABELS")
    A("--")
    A("-- Staged first, then resolved. The first attempt inserted 35,871")
    A("-- rows in ONE statement with a subquery per row, and the server")
    A("-- died on it - 36,000 subqueries in a single INSERT is more than")
    A("-- it will plan. Staging and resolving separately is both faster")
    A("-- and it lets the resolution be checked.")
    A("-- =====================================================================")
    A("")
    A("CREATE TEMP TABLE _vocab_label_stage (")
    A("  vocabulary   text NOT NULL,")
    A("  value_key    text NOT NULL,")
    A("  language     text NOT NULL,")
    A("  name         text NOT NULL,")
    A("  source       text,")
    A("  source_ref   text")
    A(") ON COMMIT DROP;")
    A("")
    A("\n".join(label_sql))
    A("-- Resolve each staged row to its value's id, by the value's own key.")
    A("-- A row whose key does not resolve is DROPPED, not left dangling.")
    for vocab, (table, keycol, extra) in TARGETS.items():
        A(f"DELETE FROM _vocab_label_stage s")
        A(f" WHERE s.vocabulary = {q(vocab)}")
        A(f"   AND NOT EXISTS (SELECT 1 FROM {table} t")
        A(f"                    WHERE t.{keycol} = s.value_key"
          + (f" AND {extra}" if extra else "") + ");")
    A("")
    # One resolved insert per vocabulary: each vocabulary's rows join
    # against its own table on its own key.
    for vocab, (table, keycol, extra) in TARGETS.items():
        if not (labels.get(vocab) or {}):
            continue
        A(f"-- resolve the {vocab} labels against {table}")
        A("INSERT INTO vocabulary_labels")
        A("  (vocabulary, value_id, language, name, is_primary, source, source_ref)")
        # is_primary: these are the Wikidata label for the value in
        # that language — the canonical one, the one the page should
        # show. There is exactly ONE label per (value, language) in
        # this table, so it is primary. It was hardcoded false, which
        # left all 35,871 rows claiming to be a secondary label of
        # nothing.
        A(f"SELECT s.vocabulary, t.id, s.language, s.name, true, s.source, s.source_ref")
        A("  FROM _vocab_label_stage s")
        A(f"  JOIN {table} t ON t.{keycol} = s.value_key"
          + (f" AND {extra}" if extra else ""))
        A(f" WHERE s.vocabulary = {q(vocab)}")
        A("ON CONFLICT (vocabulary, value_id, language) DO UPDATE SET")
        A("  name = EXCLUDED.name,")
        A("  source = EXCLUDED.source,")
        A("  source_ref = EXCLUDED.source_ref;")
        A("")
    A("COMMIT;")
    A("")
    A("\\else")
    A("\\echo 'GUS-242: the vocabulary labels are already applied - skipping'")
    A("\\endif")
    A("")

    OUT_PATH.write_text("\n".join(L))
    print(f"-> {OUT_PATH}  ({len(L)} lines)")
    MIGRATION_PATH.write_text("\n".join(L))
    print(f"-> {MIGRATION_PATH}")
    print(f"   QID updates : {len(qid_sql)}")
    print(f"   label rows  : {total_rows}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
