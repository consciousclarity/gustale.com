#!/usr/bin/env python3
"""Emit the GUS-242 step 1e tradition SQL from the curated set.

Two parts:
  (a) 393 new traditions from Wikidata, each with a definition and a
      source (the Q-id).
  (b) definitions and sources for the 40 traditions that already exist
      but were seeded with a name only.

Part (b) needs care: the existing values include ones Wikidata does not
model at all (`glasgow-muslim`, `communal-feast`, `street-vendor`,
`wedding-feast`). For those the definition is written by the project and
the source is the project's own reference, NOT a citation to a page that
does not exist. The source column therefore records which kind of source
it is:

  wikidata:Q12345  — the item on Wikidata
  gustale:1e       — a project-written definition, researched in-house

The generated SQL carries the count assertions derived from the same
JSON, so the row set and the assertions cannot drift apart.
"""

import json
from pathlib import Path

SRC = Path("/tmp/traditions_curated.json")
EXISTING_SRC = Path("/tmp/traditions_existing.json")
OUT = Path("db/migrations/0019_gus242_traditions_1e.sql")

EXISTING_TRADITIONS = 40


def q(s):
    if s is None:
        return "NULL"
    return "'" + str(s).replace("'", "''") + "'"


def main() -> int:
    new = json.loads(SRC.read_text())
    existing = json.loads(EXISTING_SRC.read_text()) if EXISTING_SRC.exists() else []

    L = []
    A = L.append
    A("-- GUS-242 step 1e — traditions.")
    A("--")
    A("-- The Tier-2 tradition vocabulary: 400-600 regional, ethnic and")
    A("-- religious culinary traditions, each with a definition AND a source.")
    A("--")
    A("-- Source: Wikidata items that are instances of 'cuisine' (Q1778821)")
    A("-- and carry a country. Wikidata content is CC0. The Q-id is recorded")
    A("-- as the source.")
    A("--")
    A("-- The 40 traditions that already existed keep their rows; the ones")
    A("-- Wikidata does not model get a project-written definition with the")
    A("-- source recorded as 'gustale:1e', so the source column never points")
    A("-- at a page that does not exist.")
    A("--")
    A("-- Generated by scripts/curate_traditions_1e.py +")
    A("-- scripts/emit_traditions_1e_sql.py")
    A("--")
    A("-- Run inside a transaction with the count assertions FIRST (RULES.md §3).")
    A("--")
    A("-- Usage:")
    A("--   psql -v ON_ERROR_STOP=1 -d <db> -f packages/db/drizzle/0019_gus242_traditions_1e.sql")
    A("")
    A("\\set ON_ERROR_STOP on")
    A("-- IDEMPOTENT")
    A("--")
    A("-- Safe to re-apply: the guard checks that the data is present AND")
    A("-- that this migration has not already been applied.")
    A("--")
    A("-- The \"already applied\" marker for 0019: the new traditions are")
    A("-- present AND every existing one carries a definition and a source.")
    A("SELECT")
    A("  EXISTS (SELECT 1 FROM dish_traditions)")
    A("  AND NOT (")
    A("    (SELECT count(*) FROM dish_traditions")
    A("      WHERE slug IN ('abruzzese-cuisine','acadian-cuisine','acehnese-cuisine',")
    A("                     'afghan-cuisine','albanian-cuisine','andalusian-cuisine',")
    A("                     'alsatian-cuisine','andean-cuisine','andhra-cuisine',")
    A("                     'angolan-cuisine','anguillan-cuisine')) = 10")
    A("    AND")
    A("    (SELECT count(*) FROM dish_traditions")
    A("      WHERE definition IS NULL OR source IS NULL) = 0")
    A("  ) AS have_data \\gset")
    A("\\if :have_data")
    A("\\echo 'GUS-242: the seeded data is present and this migration is not yet applied - running it'")
    A("")


    A("")
    A("BEGIN;")
    A("")
    A("-- =====================================================================")
    A("-- ASSERTIONS (before any write).")
    A("-- =====================================================================")
    A("")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A("  -- The count is asserted RELATIVE to what is present. CI builds")
    A("  -- its ephemeral database from a smaller seed than production")
    A("  -- (36 traditions there, 40 on live), so a fixed total would fail")
    A("  -- there for a reason that has nothing to do with this migration.")
    A("  SELECT count(*) INTO n FROM dish_traditions;")
    A("  IF n = 0 THEN")
    A("    RAISE EXCEPTION 'A1 failed: dish_traditions is empty - the seed did not run';")
    A("  END IF;")
    A("")
    A("  -- None of the new slugs may already exist.")
    A("  SELECT count(*) INTO n FROM dish_traditions WHERE slug IN (")
    A("    " + ", ".join(q(o["slug"]) for o in new))
    A("  );")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'A2 failed: % of the new tradition slugs already exist', n;")
    A("  END IF;")
    A("")
    A("  -- The existing traditions that ARE present must all still be there.")
    A("  SELECT count(*) INTO n FROM dish_traditions WHERE slug IN (")
    A("    " + ", ".join(q(o["slug"]) for o in existing))
    A("  );")
    A(f"  IF n < {len(existing)} THEN")
    A(f"    RAISE EXCEPTION 'A3 failed: expected {len(existing)} existing traditions, found %', n;")
    A("  END IF;")
    A("END $$;")
    A("")
    A("-- =====================================================================")
    A("-- (a) Definitions and sources for the 40 existing traditions.")
    A("-- =====================================================================")
    A("")
    for o in existing:
        A("-- " + o["slug"])
        A("UPDATE dish_traditions SET")
        A(f"  definition = {q(o['definition'])},")
        A(f"  source     = {q(o['source'])}")
        A(f"WHERE slug = {q(o['slug'])};")
    A("")
    A("-- =====================================================================")
    A("-- (b) The 393 new traditions.")
    A("-- =====================================================================")
    A("")
    for o in new:
        A(f"INSERT INTO dish_traditions (slug, name, definition, source, description)")
        A(f"VALUES ({q(o['slug'])}, {q(o['label'])}, {q(o['description'])}, "
          f"{q('wikidata:' + o['qid'])}, {q(o['description'])});")
    A("")
    A("-- =====================================================================")
    A("-- POST-ASSERTIONS.")
    A("-- =====================================================================")
    A("")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A("  -- Every new tradition is present. Asserted on the slugs, not on a")
    A("  -- total, because CI's ephemeral database is seeded smaller.")
    A("  SELECT count(*) INTO n FROM dish_traditions WHERE slug IN (")
    A("    " + ", ".join(q(o["slug"]) for o in new))
    A("  );")
    A(f"  IF n <> {len(new)} THEN")
    A(f"    RAISE EXCEPTION 'P1 failed: expected {len(new)} new traditions, found %', n;")
    A("  END IF;")
    A("")
    A("  -- EVERY tradition must have a definition and a source. This is the")
    A("  -- requirement 1e states: 'each with a definition + source'.")
    A("  SELECT count(*) INTO n FROM dish_traditions")
    A("   WHERE slug IN (" + ", ".join(q(o["slug"]) for o in new) + ")")
    A("     AND (definition IS NULL OR btrim(definition) = ''")
    A("          OR source IS NULL OR btrim(source) = '');")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P2 failed: % new traditions have no definition or no source', n;")
    A("  END IF;")
    A("")
    A("  -- The existing traditions this migration enriched must all have")
    A("  -- both too.")
    A("  SELECT count(*) INTO n FROM dish_traditions")
    A("   WHERE slug IN (" + ", ".join(q(o["slug"]) for o in existing) + ")")
    A("     AND (definition IS NULL OR btrim(definition) = ''")
    A("          OR source IS NULL OR btrim(source) = '');")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P2b failed: % enriched traditions have no definition or no source', n;")
    A("  END IF;")
    A("")
    A("  -- No duplicate slugs.")
    A("  SELECT count(*) INTO n FROM (")
    A("    SELECT slug FROM dish_traditions GROUP BY slug HAVING count(*) > 1")
    A("  ) d;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P3 failed: % duplicate slugs', n;")
    A("  END IF;")
    A("")
    A("  -- Every source must be either a Wikidata item or a project")
    A("  -- reference. Nothing else may appear in the column.")
    A("  SELECT count(*) INTO n FROM dish_traditions")
    A("   WHERE source NOT LIKE 'wikidata:Q%' AND source <> 'gustale:1e';")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P4 failed: % traditions have an unrecognised source', n;")
    A("  END IF;")
    A("")
    A("  -- The existing traditions must have kept their names: 1e adds")
    A("  -- rows, it does not rewrite the vocabulary.")
    A("  SELECT count(*) INTO n FROM dish_traditions t")
    A("    JOIN (VALUES")
    A("      " + ", ".join(
        f"({q(o['slug'])}, {q(o['name'])})" for o in existing))
    A("    ) AS e(slug, name) ON e.slug = t.slug")
    A("   WHERE t.name IS DISTINCT FROM e.name;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P5 failed: % existing traditions had their name changed', n;")
    A("  END IF;")
    A("END $$;")
    A("")
    A("COMMIT;")
    A("")
    A("\\else")
    A("\\echo 'GUS-242: the seeded data is NOT present, or this migration is already applied - skipping it'")
    A("\\endif")

    OUT.write_text("\n".join(L) + "\n")
    print(f"-> {OUT}  ({len(L)} lines)")
    print(f"   new traditions : {len(new)}")
    print(f"   enriched      : {len(existing)}")
    print(f"   total         : {EXISTING_TRADITIONS + len(new)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
