#!/usr/bin/env python3
"""Load the fetched dish names into the dish_names table.

The input is /tmp/dish_names.json, produced by
scripts/fetch_dish_names.py:

    { dish_slug: [ {language, script, name, kind, is_primary}, ... ] }

One row per (dish, language, script, name). The dish_id is resolved by
a subquery on the dish's slug, so the SQL does not depend on the UUIDs
being stable between the export and the apply.

ENGLISH IS NOT WRITTEN. The dish's English name is its canonical_name
in the dishes table, which is exactly what the ADR says: the base
table holds the canonical name and the translations table holds the
others. So the English exonym is dropped here, and only the non-English
names are written.

Output: db/migrations/0024_adr003_dish_names_data.sql
"""

import json
import pathlib

NAMES_PATH = pathlib.Path("/tmp/dish_names.json")
OUT_PATH = pathlib.Path("db/migrations/0024_adr003_dish_names_data.sql")


def q(s):
    return "'" + str(s).replace("'", "''") + "'"


def main():
    if not NAMES_PATH.exists():
        print(f"ERROR: {NAMES_PATH} does not exist - run fetch_dish_names.py first")
        return 1

    names = json.loads(NAMES_PATH.read_text())

    rows = []
    dropped_english = 0
    for slug, entries in names.items():
        for entry in entries:
            language = entry["language"]
            if language == "en":
                # The English name is the dish's canonical_name, which
                # lives in the dishes table.
                dropped_english += 1
                continue
            name = (entry.get("name") or "").strip()
            if not name:
                continue
            rows.append(
                f"  ({q(slug)}, {q(language)}, "
                f"{q(entry.get('script')) if entry.get('script') else 'NULL'}, "
                f"{q(name)}, {q(entry.get('kind') or 'endonym')}, "
                f"{'true' if entry.get('is_primary') else 'false'}, "
                f"'wikidata')"
            )

    L = []
    A = L.append
    A("-- GUS-242 / ADR-003 layer 2 — the dish names.")
    A("--")
    A("-- Generated by scripts/load_dish_names.py from /tmp/dish_names.json.")
    A("-- Do not hand-edit: regenerate.")
    A("--")
    A(f"-- {len(rows)} names, seeded from Wikidata (CC0): the sitelink titles")
    A("-- for the endonyms, P1705 for the native labels, P2561 for the")
    A("-- romanizations and P1448 for the official names, plus the item's")
    A("-- labels for the exonyms.")
    A("--")
    A("-- ENGLISH IS NOT HERE: the dish's English name is its canonical_name")
    A("-- in the dishes table, which is what the ADR asks for - the base")
    A("-- table holds the canonical name and this table holds the others.")
    A(f"-- ({dropped_english} English names were dropped for that reason.)")
    A("--")
    A("-- The dish_id is resolved by a subquery on the dish's slug, so the")
    A("-- SQL does not depend on the UUIDs being stable between the export")
    A("-- and the apply.")
    A("--")
    A("-- Idempotent: re-running changes no row.")
    A("")
    A("\\set ON_ERROR_STOP on")
    A("")
    A("-- IDEMPOTENT")
    A("--")
    A("-- The guard is TRUE when the migration still needs to run - that is,")
    A("-- when the names are not yet there.")
    A("SELECT")
    A("  NOT (")
    A("    (SELECT count(*) FROM dish_names) >= 1000")
    A("    AND")
    A("    (SELECT count(DISTINCT dish_id) FROM dish_names) >= 100")
    A("  ) AS need_to_run \\gset")
    A("\\if :need_to_run")
    A("\\echo 'GUS-242: the dish names are not yet applied - applying them'")
    A("")
    A("BEGIN;")
    A("")
    A("INSERT INTO dish_names")
    A("  (dish_id, language, script, name, kind, is_primary, source)")
    A("SELECT d.id, v.language, v.script, v.name, v.kind, v.is_primary, v.source")
    A("  FROM (VALUES")
    A(",\n".join(rows))
    A("  ) AS v(dish_slug, language, script, name, kind, is_primary, source)")
    A("  JOIN dishes d ON d.slug = v.dish_slug")
    A("ON CONFLICT (dish_id, language, script, name) DO UPDATE SET")
    A("  kind = EXCLUDED.kind,")
    A("  is_primary = EXCLUDED.is_primary,")
    A("  source = EXCLUDED.source;")
    A("")
    A("COMMIT;")
    A("")
    A("\\else")
    A("\\echo 'GUS-242: the dish names are already applied - skipping'")
    A("\\endif")
    A("")

    OUT_PATH.write_text("\n".join(L))
    print(f"-> {OUT_PATH}  ({len(L)} lines)")
    print(f"   name rows        : {len(rows)}")
    print(f"   English dropped  : {dropped_english}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
