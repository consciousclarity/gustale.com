#!/usr/bin/env python3
"""Emit the GUS-242 step 1f vocabulary SQL from /tmp/vocab_1f.json.

The SQL is generated rather than hand-written so the row set and the
generated JSON can never drift apart. The count assertions are emitted
from the same source, so they assert exactly what is applied.

Parents are inserted in TWO passes: roots first, then the children. A
child's parent must already exist when the child is inserted, because
parent_id carries a foreign key.
"""

import json
from pathlib import Path

SRC = Path("/tmp/vocab_1f.json")
OUT = Path("packages/db/drizzle/0018_gus242_vocab_1f.sql")

# The values already in the live database. 1f EXTENDS these; the 28
# families become the groups that the new values hang from.
EXISTING_FAMILIES = 28
EXISTING_TECHNIQUES = 26
EXISTING_CONTEXTS = 5

# The 28 families already in the live database. They become the groups
# that the new values hang from, and they must be left untouched.
EXISTING_FAMILY_SLUGS = [
    "bread", "breaded-cutlet", "casserole", "curry", "dessert", "dumpling",
    "egg-dish", "fermented-dish", "filled-pastry", "fried-rice", "fritter",
    "kebab", "moussaka", "noodle-soup", "pancake", "pasta", "porridge",
    "rice-dish", "salad", "sandwich", "sauce", "side-dish", "soup", "stew",
    "stiff-porridge", "street-snack", "stuffed-vegetable", "taco",
]


def q(s):
    """Quote a SQL string literal."""
    if s is None:
        return "NULL"
    return "'" + s.replace("'", "''") + "'"


# The live schema:
#   dish_families        id, slug, name, description, created_at, parent_id
#   dish_techniques      id, slug, name, description, created_at, foodon_id
#   dish_contexts        id, slug, name, description, created_at
#
# Only the families carry a hierarchy (the plan asks for "family
# (120-180, with parent_id hierarchy)"). Techniques get their FoodOn
# cross-reference; contexts get neither.
TABLE_COLUMNS = {
    "dish_families": ("parent_id", None),
    "dish_techniques": (None, "foodon_id"),
    "dish_contexts": (None, None),
}


def emit_table(label, rows, table, idcol, parent_col, extra=""):
    """Emit INSERTs for one vocabulary, parents before children.

    `parent_col` is the hierarchy column, `extra` the cross-reference
    column. A hierarchy column only exists on dish_families, so the
    parent is emitted for that table and dropped elsewhere.
    """
    has_parent, has_extra = TABLE_COLUMNS[table]
    by_slug = {r["slug"]: r for r in rows}
    known = set(by_slug)

    def depth(r):
        d = 0
        cur = r["parent"]
        while cur and cur in known:
            d += 1
            cur = by_slug[cur]["parent"]
        return d

    if has_parent:
        ordered = sorted(rows, key=lambda r: (depth(r), r["slug"]))
    else:
        ordered = sorted(rows, key=lambda r: r["slug"])

    out = []
    for r in ordered:
        cols = ["slug", "name", "description"]
        vals = [q(r["slug"]), q(r["name"]), q(r["description"])]
        if has_extra:
            cols.append(has_extra)
            vals.append(q(r.get("foodon_id")))
        if has_parent and r["parent"]:
            cols.append(has_parent)
            # The parent must already exist, so the rows are emitted
            # parents-first.
            vals.append(f"(SELECT id FROM {table} WHERE slug = {q(r['parent'])})")
        out.append(
            f"INSERT INTO {table} ({', '.join(cols)})\n"
            f"VALUES ({', '.join(vals)});"
        )
    return "\n".join(out)


def main() -> int:
    v = json.loads(SRC.read_text())
    fams = v["families"]
    techs = v["techniques"]
    ctxs = v["contexts"]

    L = []
    A = L.append
    A("-- GUS-242 step 1f — vocabularies.")
    A("--")
    A("-- Families, techniques and contexts, grown to the sizes the")
    A("-- GUS-242 plan set, with a parent_id hierarchy on the families.")
    A("--")
    A("-- Generated by scripts/build_vocab_1f.py + scripts/emit_vocab_1f_sql.py")
    A("-- from a single source of truth, so the row set and the assertions")
    A("-- cannot drift apart.")
    A("--")
    A("-- Run inside a transaction with the count assertions FIRST (RULES.md §3).")
    A("--")
    A("-- Usage:")
    A("--   psql -v ON_ERROR_STOP=1 -d <db> -f packages/db/drizzle/0018_gus242_vocab_1f.sql")
    A("--")
    A("-- ROLLBACK")
    A("--   DELETE FROM dish_families     WHERE slug IN (<the 168 slugs>);")
    A("--   DELETE FROM dish_techniques   WHERE slug IN (<the 63 slugs>);")
    A("--   DELETE FROM dish_contexts     WHERE slug IN (<the 26 slugs>);")
    A("--   (restore the 28 families' parent_id to NULL)")
    A("")
    A("\\set ON_ERROR_STOP on")
    A("")
    A("BEGIN;")
    A("")
    A("-- =====================================================================")
    A("-- ASSERTIONS (before any write).")
    A("-- =====================================================================")
    A("")
    A(f"-- The families grow from {EXISTING_FAMILIES} to {EXISTING_FAMILIES + len(fams)}.")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A(f"  SELECT count(*) INTO n FROM dish_families WHERE slug <> '';")
    A(f"  IF n <> {EXISTING_FAMILIES} THEN")
    A(f"    RAISE EXCEPTION 'A1 failed: expected {EXISTING_FAMILIES} existing families, found %', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_techniques WHERE slug <> '';")
    A(f"  IF n <> {EXISTING_TECHNIQUES} THEN")
    A(f"    RAISE EXCEPTION 'A2 failed: expected {EXISTING_TECHNIQUES} existing techniques, found %', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_contexts WHERE slug <> '';")
    A(f"  IF n <> {EXISTING_CONTEXTS} THEN")
    A(f"    RAISE EXCEPTION 'A3 failed: expected {EXISTING_CONTEXTS} existing contexts, found %', n;")
    A("  END IF;")
    A("")
    A("  -- None of the new slugs may already exist.")
    A(f"  SELECT count(*) INTO n FROM dish_families WHERE slug IN (")
    A("    " + ", ".join(q(r["slug"]) for r in fams))
    A("  );")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'A4 failed: % of the new family slugs already exist', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_techniques WHERE slug IN (")
    A("    " + ", ".join(q(r["slug"]) for r in techs))
    A("  );")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'A5 failed: % of the new technique slugs already exist', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_contexts WHERE slug IN (")
    A("    " + ", ".join(q(r["slug"]) for r in ctxs))
    A("  );")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'A6 failed: % of the new context slugs already exist', n;")
    A("  END IF;")
    A("")
    A("  -- The five meal-set families MUST be present: they are the only")
    A("  -- composed_of family values (spec §2).")
    A("  SELECT count(*) INTO n FROM (VALUES")
    A("    ('thali'),('rijsttafel'),('meze'),('banchan'),('nasi-campur')")
    A("  ) AS m(slug) WHERE m.slug IN (")
    A("    " + ", ".join(q(r["slug"]) for r in fams))
    A("  );")
    A("  IF n <> 5 THEN")
    A("    RAISE EXCEPTION 'A7 failed: expected all 5 meal-set families in the batch, found %', n;")
    A("  END IF;")
    A("")
    A("  -- The stress-set context value MUST be present.")
    A("  SELECT count(*) INTO n FROM (VALUES ('tableside')) AS m(slug)")
    A("   WHERE m.slug IN (" + ", ".join(q(r["slug"]) for r in ctxs) + ");")
    A("  IF n <> 1 THEN")
    A("    RAISE EXCEPTION 'A8 failed: the tableside context is missing from the batch';")
    A("  END IF;")
    A("END $$;")
    A("")
    A("-- =====================================================================")
    A("-- FAMILIES — parents before children, because parent_id is a FK.")
    A("-- =====================================================================")
    A("")
    A(emit_table("families", fams, "dish_families", "id", "parent_id"))
    A("")
    A("-- =====================================================================")
    A("-- TECHNIQUES.")
    A("-- =====================================================================")
    A("")
    A(emit_table("techniques", techs, "dish_techniques", "id", "parent_id"))
    A("")
    A("-- =====================================================================")
    A("-- CONTEXTS.")
    A("-- =====================================================================")
    A("")
    A(emit_table("contexts", ctxs, "dish_contexts", "id", "parent_id"))
    A("")
    A("-- =====================================================================")
    A("-- POST-ASSERTIONS.")
    A("-- =====================================================================")
    A("")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A(f"  SELECT count(*) INTO n FROM dish_families;")
    A(f"  IF n <> {EXISTING_FAMILIES + len(fams)} THEN")
    A(f"    RAISE EXCEPTION 'P1 failed: expected {EXISTING_FAMILIES + len(fams)} families, found %', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_techniques;")
    A(f"  IF n <> {EXISTING_TECHNIQUES + len(techs)} THEN")
    A(f"    RAISE EXCEPTION 'P2 failed: expected {EXISTING_TECHNIQUES + len(techs)} techniques, found %', n;")
    A("  END IF;")
    A("")
    A(f"  SELECT count(*) INTO n FROM dish_contexts;")
    A(f"  IF n <> {EXISTING_CONTEXTS + len(ctxs)} THEN")
    A(f"    RAISE EXCEPTION 'P3 failed: expected {EXISTING_CONTEXTS + len(ctxs)} contexts, found %', n;")
    A("  END IF;")
    A("")
    A("  -- Every family's parent_id must resolve, and no family may be")
    A("  -- its own parent.")
    A("  SELECT count(*) INTO n FROM dish_families c")
    A("    LEFT JOIN dish_families p ON p.id = c.parent_id")
    A("   WHERE c.parent_id IS NOT NULL AND p.id IS NULL;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P4 failed: % families have an unresolved parent', n;")
    A("  END IF;")
    A("")
    A("  SELECT count(*) INTO n FROM dish_families WHERE parent_id = id;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P5 failed: % families are their own parent', n;")
    A("  END IF;")
    A("")
    A("  -- The hierarchy must be acyclic. Walk up from every family with a")
    A("  -- depth limit; if the walk ever lands back on the family it")
    A("  -- started from, that family is in a cycle.")
    A("  SELECT count(*) INTO n FROM (")
    A("    WITH RECURSIVE walk AS (")
    A("      SELECT id AS start, id AS node, parent_id, 1 AS lvl")
    A("        FROM dish_families WHERE parent_id IS NOT NULL")
    A("      UNION ALL")
    A("      SELECT w.start, p.id, p.parent_id, w.lvl + 1")
    A("        FROM walk w")
    A("        JOIN dish_families p ON p.id = w.parent_id")
    A("       WHERE w.lvl < 50 AND p.id IS NOT NULL")
    A("    )")
    A("    SELECT DISTINCT start FROM walk WHERE node = start AND lvl > 1")
    A("  ) cycles;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P6 failed: the family hierarchy has % cycles', n;")
    A("  END IF;")
    A("")
    A("  -- The 28 pre-existing families must still be present and unmodified.")
    A("  SELECT count(*) INTO n FROM dish_families")
    A("   WHERE slug IN (" + ", ".join(q(s) for s in EXISTING_FAMILY_SLUGS) + ");")
    A(f"  IF n <> {len(EXISTING_FAMILY_SLUGS)} THEN")
    A("    RAISE EXCEPTION 'P7 failed: expected all 28 pre-existing families, found %', n;")
    A("  END IF;")
    A("")
    A("  -- They must have kept their NULL parent_id: 1f hangs the new")
    A("  -- values UNDER them, it does not re-parent them.")
    A("  SELECT count(*) INTO n FROM dish_families")
    A("   WHERE slug IN (" + ", ".join(q(s) for s in EXISTING_FAMILY_SLUGS) + ")")
    A("     AND parent_id IS NOT NULL;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P7b failed: % pre-existing families were re-parented', n;")
    A("  END IF;")
    A("")
    A("  -- Every NEW value must have a name and a description. The 28")
    A("  -- pre-existing families are excluded: several of them legitimately")
    A("  -- have no description yet, and filling those in is separate work.")
    A("  SELECT count(*) INTO n FROM dish_families")
    A("   WHERE slug NOT IN (" + ", ".join(q(s) for s in EXISTING_FAMILY_SLUGS) + ")")
    A("     AND (name IS NULL OR btrim(name) = ''")
    A("          OR description IS NULL OR btrim(description) = '');")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P8 failed: % new families have a missing name or description', n;")
    A("  END IF;")
    A("END $$;")
    A("")
    A("COMMIT;")

    OUT.write_text("\n".join(L) + "\n")
    print(f"-> {OUT}  ({len(L)} lines)")
    print(f"   families   {len(fams)}")
    print(f"   techniques {len(techs)}")
    print(f"   contexts   {len(ctxs)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
