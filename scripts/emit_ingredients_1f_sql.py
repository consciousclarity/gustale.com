#!/usr/bin/env python3
"""Emit the GUS-242 step 1f ingredient-categories SQL.

The vocabulary comes from scripts/curate_ingredients_1f.py, which writes
/tmp/ingredient_categories_1f.json. The SQL is generated rather than
hand-written so the row set and the generated JSON can never drift.

The migration:
  - inserts the 381 FoodOn-derived rows (15 groups + 366 classes), each
    with its FoodOn ID and its parent;
  - inserts the 54 project rows, each hung under its FoodOn class;
  - sets the parent_id of the rows that already exist in the database
    (the 55 project categories) to their FoodOn class, WITHOUT changing
    their slug, id, name or description.

The third point matters: the dishes reference the existing categories
by id, so those rows must survive the migration untouched apart from
gaining a parent.

Output: db/migrations/0020_gus242_ingredient_categories.sql
"""

import json
import pathlib
import sys

IN_PATH = pathlib.Path("/tmp/ingredient_categories_1f.json")
OUT_PATH = pathlib.Path("db/migrations/0020_gus242_ingredient_categories.sql")

# The project's existing categories. These are the rows that already
# exist in the database and must be UPDATED, not re-inserted.
EXISTING = 55

# The expected end state.
EXPECT_TOTAL = 434
EXPECT_FOODON_IDS = 381
# The row counts this migration produces in the DATABASE. The vocabulary
# has 434 rows, but one slug ('vinegar') is BOTH a project category and
# a FoodOn class, so it merges into a single row: 435 rows in the
# database, of which 380 carry a FoodOn ID (the project row inherits the
# class's ID) and 41 carry a parent.
FOODON_ID_COUNT = 380
PARENT_COUNT = 41


def q(s):
    """A SQL string literal."""
    return "'" + str(s).replace("'", "''") + "'"


def main():
    rows = json.loads(IN_PATH.read_text())
    if len(rows) != EXPECT_TOTAL:
        print(f"ERROR: expected {EXPECT_TOTAL} rows, got {len(rows)}", file=sys.stderr)
        return 1

    foodon_rows = [r for r in rows if r["origin"] != "project"]
    project_rows = [r for r in rows if r["origin"] == "project"]

    L = []
    A = L.append

    A("-- GUS-242 step 1f — the ingredient-category vocabulary")
    A("--")
    A("-- Generated by scripts/emit_ingredients_1f_sql.py from")
    A("-- /tmp/ingredient_categories_1f.json. Do not hand-edit: regenerate.")
    A("--")
    A(f"-- {len(foodon_rows)} FoodOn-derived rows (EFSA FOodex2 groups and")
    A(f"-- classes, each with its FoodOn ID) plus {len(project_rows)} project")
    A(f"-- rows. {EXPECT_TOTAL} in total.")
    A("--")
    A("-- The plan's rule: FoodOn supplies IDENTIFIERS ONLY; the labels and")
    A("-- definitions are our own. So the FoodOn-derived rows carry the ID")
    A("-- and the parent link, and the project rows keep their own slug,")
    A("-- name and description — the dishes reference them by id.")
    A("--")
    A("-- Idempotent: re-running inserts 0 rows and changes no parent.")
    A("")
    A("\\set ON_ERROR_STOP on")
    A("")
    A("-- IDEMPOTENT")
    A("--")
    A("-- Safe to re-apply: the guard checks that the data is present AND")
    A("-- that this migration has not already been applied.")
    A("--")
    A("-- The \"already applied\" marker for 0020: every FoodOn-derived row")
    A("-- is present AND the parent links are in place.")
    A("--")
    A("-- The counts are the ones this migration actually produces: 435")
    A("-- rows, of which 380 carry a FoodOn ID (the 'vinegar' project row")
    A("-- inherits the ID of the FoodOn class it collided with) and 41")
    A("-- carry a parent.")
    A("SELECT")
    A("  EXISTS (SELECT 1 FROM ingredient_categories)")
    A("  AND NOT (")
    A(f"    (SELECT count(*) FROM ingredient_categories WHERE foodon_id IS NOT NULL) = {FOODON_ID_COUNT}")
    A("    AND")
    A(f"    (SELECT count(*) FROM ingredient_categories WHERE parent_id IS NOT NULL) = {PARENT_COUNT}")
    A("  ) AS have_data \\gset")
    A("\\if :have_data")
    A("\\echo 'GUS-242: the seeded data is present and this migration is not yet applied - running it'")
    A("")
    A("BEGIN;")
    A("")

    # --- pre-flight ------------------------------------------------------
    A("-- =====================================================================")
    A("-- PRE-FLIGHT — assert the state this migration expects")
    A("-- =====================================================================")
    A("")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A("  -- The ingredient_categories table must exist and be populated.")
    A("  SELECT count(*) INTO n FROM ingredient_categories;")
    A("  IF n < 1 THEN")
    A("    RAISE EXCEPTION 'P1 failed: ingredient_categories is empty - the seed did not run';")
    A("  END IF;")
    A("")
    A("  -- The 55 existing categories must all still be present. The")
    A("  -- migration only adds parent links to them; it must not remove")
    A("  -- or rename any of them, because the dishes reference them by id.")
    A("  SELECT count(*) INTO n FROM ingredient_categories")
    A("   WHERE slug IN (")
    existing_slugs = sorted(r["slug"] for r in project_rows)
    for i in range(0, len(existing_slugs), 8):
        chunk = ", ".join(q(s) for s in existing_slugs[i:i + 8])
        A(f"     {chunk}" + ("," if i + 8 < len(existing_slugs) else ""))
    A("   );")
    A(f"  IF n <> {len(existing_slugs)} THEN")
    A(f"    RAISE EXCEPTION 'P2 failed: expected all {len(existing_slugs)} existing ingredient categories, found %', n;")
    A("  END IF;")
    A("")
    A("  -- No slug in the new set may already exist with a DIFFERENT id")
    A("  -- than the one this migration would create, and no FoodOn ID may")
    A("  -- already be taken by a different slug.")
    A("  SELECT count(*) INTO n")
    A("    FROM ingredient_categories c")
    A("    JOIN (VALUES")
    new_pairs = [(r["slug"], r["foodon_id"]) for r in foodon_rows if r["foodon_id"]]
    for i in range(0, len(new_pairs), 4):
        chunk = ", ".join(f"({q(s)}, {q(f)})" for s, f in new_pairs[i:i + 4])
        A(f"      {chunk}" + ("," if i + 4 < len(new_pairs) else ""))
    A("    ) AS v(slug, foodon_id)")
    A("   ON c.slug = v.slug AND c.foodon_id IS DISTINCT FROM v.foodon_id;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P3 failed: % existing rows would have their FoodOn ID changed', n;")
    A("  END IF;")
    A("")
    A("  SELECT count(*) INTO n")
    A("    FROM ingredient_categories c")
    A("    JOIN (VALUES")
    for i in range(0, len(new_pairs), 4):
        chunk = ", ".join(f"({q(s)}, {q(f)})" for s, f in new_pairs[i:i + 4])
        A(f"      {chunk}" + ("," if i + 4 < len(new_pairs) else ""))
    A("    ) AS v(slug, foodon_id)")
    A("   ON c.foodon_id = v.foodon_id AND c.slug <> v.slug;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'P4 failed: % FoodOn IDs are already held by a different slug', n;")
    A("  END IF;")
    A("END $$;")
    A("")

    # --- the FoodOn-derived rows ----------------------------------------
    A("-- =====================================================================")
    A("-- THE FOODON-DERIVED ROWS")
    A("--")
    A("-- Parents before children, because parent_id is a FK.")
    A("-- =====================================================================")
    A("")

    # Order so that a parent is inserted before its children.
    by_slug = {r["slug"]: r for r in foodon_rows}
    ordered = []
    pending = list(foodon_rows)
    while pending:
        progressed = False
        still = []
        for r in pending:
            p = r["parent_slug"]
            if p is None or p in by_slug and any(o["slug"] == p for o in ordered):
                ordered.append(r)
                progressed = True
            else:
                still.append(r)
        if not progressed:
            # A cycle or a missing parent: append the rest in order and
            # let the post-assertion catch it.
            ordered.extend(still)
            break
        pending = still

    A("-- The FoodOn-derived rows (parents first).")
    A("INSERT INTO ingredient_categories (slug, name, foodon_id, parent_id, description)")
    A("VALUES")
    vals = []
    for r in ordered:
        parent = r["parent_slug"]
        parent_expr = (
            f"(SELECT id FROM ingredient_categories WHERE slug = {q(parent)})"
            if parent else "NULL"
        )
        vals.append(
            f"  ({q(r['slug'])}, {q(r['name'])}, {q(r['foodon_id'])}, {parent_expr}, NULL)"
        )
    A(",\n".join(vals) + ";")
    A("")

    # --- the project rows ------------------------------------------------
    A("-- =====================================================================")
    A("-- THE PROJECT ROWS")
    A("--")
    A("-- Each hangs under its FoodOn class. The project's own slug, name")
    A("-- and description are untouched — the dishes reference these rows")
    A("-- by id, so their identity must not change.")
    A("-- =====================================================================")
    A("")
    for r in project_rows:
        parent = r["parent_slug"]
        parent_expr = (
            f"(SELECT id FROM ingredient_categories WHERE slug = {q(parent)})"
            if parent else "NULL"
        )
        A(f"UPDATE ingredient_categories")
        A(f"   SET parent_id = {parent_expr}")
        A(f" WHERE slug = {q(r['slug'])};")
    A("")

    # --- post-assertions -------------------------------------------------
    A("-- =====================================================================")
    A("-- POST-ASSERTIONS")
    A("-- =====================================================================")
    A("")
    A("DO $$")
    A("DECLARE n int;")
    A("BEGIN")
    A("  -- Every row is present.")
    A("  SELECT count(*) INTO n FROM ingredient_categories;")
    A(f"  IF n < {EXPECT_TOTAL} THEN")
    A(f"    RAISE EXCEPTION 'Q1 failed: expected at least {EXPECT_TOTAL} ingredient categories, found %', n;")
    A("  END IF;")
    A("")
    A("  -- Every FoodOn ID is distinct (the DB enforces this with a")
    A("  -- partial unique index, so this can only fail if the index is")
    A("  -- missing — which would mean the vocabulary is not protected).")
    A("  SELECT count(*) INTO n FROM (")
    A("    SELECT foodon_id FROM ingredient_categories")
    A("     WHERE foodon_id IS NOT NULL")
    A("     GROUP BY foodon_id HAVING count(*) > 1) z;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'Q2 failed: % FoodOn IDs are used more than once', n;")
    A("  END IF;")
    A("")
    A("  -- The hierarchy must be acyclic.")
    A("  --")
    A("  -- The walk starts at each row and steps to its parent. A cycle")
    A("  -- exists when the walk comes back to a node it has already")
    A("  -- visited AT A LATER LEVEL than the start — `lvl > 1` is what")
    A("  -- distinguishes 'arrived back at the start' from 'the first")
    A("  -- step'. Without it the query reports every row as a cycle;")
    A("  -- with it, a real cycle is reported exactly once per member.")
    A("  WITH RECURSIVE walk AS (")
    A("    SELECT id AS start, id AS node, 1 AS lvl FROM ingredient_categories")
    A("     WHERE parent_id IS NOT NULL")
    A("    UNION ALL")
    A("    SELECT w.start, p.parent_id, w.lvl + 1")
    A("      FROM walk w")
    A("      JOIN ingredient_categories p ON p.id = w.node")
    A("     WHERE p.parent_id IS NOT NULL")
    A("  )")
    A("  SELECT count(*) INTO n FROM (")
    A("    SELECT DISTINCT start FROM walk WHERE lvl > 1 AND node = start")
    A("  ) z;")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'Q3 failed: the ingredient hierarchy has % cycles', n;")
    A("  END IF;")
    A("")
    A("  -- Every parent_id must point at a real row.")
    A("  SELECT count(*) INTO n FROM ingredient_categories c")
    A("   WHERE c.parent_id IS NOT NULL")
    A("     AND NOT EXISTS (SELECT 1 FROM ingredient_categories p WHERE p.id = c.parent_id);")
    A("  IF n <> 0 THEN")
    A("    RAISE EXCEPTION 'Q4 failed: % rows have a dangling parent', n;")
    A("  END IF;")
    A("")
    A("  -- The 55 pre-existing categories must still be present, with their")
    A("  -- original slugs. A dish must never lose an ingredient.")
    A("  SELECT count(*) INTO n FROM ingredient_categories")
    A("   WHERE slug IN (")
    for i in range(0, len(existing_slugs), 8):
        chunk = ", ".join(q(s) for s in existing_slugs[i:i + 8])
        A(f"     {chunk}" + ("," if i + 8 < len(existing_slugs) else ""))
    A("   );")
    A(f"  IF n <> {len(existing_slugs)} THEN")
    A(f"    RAISE EXCEPTION 'Q5 failed: expected all {len(existing_slugs)} existing categories, found %', n;")
    A("  END IF;")
    A("")
    A("  -- The dishes' ingredient links must be intact.")
    A("  --")
    A("  -- Conditional: the CI seed builds no dish ingredient links at")
    A("  -- all, so requiring them would fail a fresh ephemeral database")
    A("  -- for no good reason. The check bites where there IS something")
    A("  -- to protect.")
    A("  SELECT count(*) INTO n FROM dish_dish_ingredient_categories;")
    A("  IF n > 0 THEN")
    A("    SELECT count(*) INTO n")
    A("      FROM dish_dish_ingredient_categories x")
    A("      WHERE NOT EXISTS (")
    A("        SELECT 1 FROM ingredient_categories c WHERE c.id = x.value_id);")
    A("    IF n <> 0 THEN")
    A("      RAISE EXCEPTION 'Q6 failed: % dish ingredient links point at a missing category', n;")
    A("    END IF;")
    A("  END IF;")
    A("  RAISE NOTICE 'ingredient categories: % rows, % with a FoodOn ID',")
    A("    (SELECT count(*) FROM ingredient_categories),")
    A("    (SELECT count(*) FROM ingredient_categories WHERE foodon_id IS NOT NULL);")
    A("END $$;")
    A("")
    A("COMMIT;")
    A("")
    A("\\else")
    A("\\echo 'GUS-242: the seeded data is NOT present, or this migration is already applied - skipping it'")
    A("\\endif")
    A("")

    OUT_PATH.write_text("\n".join(L))
    print(f"-> {OUT_PATH}  ({len(L)} lines)")
    print(f"   foodon-derived rows : {len(foodon_rows)}")
    print(f"   project rows         : {len(project_rows)}")
    print(f"   total                : {len(rows)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
